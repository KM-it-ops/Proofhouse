class _Budget:
    def __init__(self, limit: str | None) -> None:
        try:
            self.left = Decimal(limit) if limit is not None else None
        except InvalidOperation:
            raise StudioError("--max-cost-usd must be a decimal such as 5.00") from None
        self.spent = Decimal(0)

    def next_limit(self) -> str | None:
        if self.left is None:
            return None
        # nothing left still asks the spend gate: a call on this machine is free and goes through, a paid one is
        # refused there, and that refusal stops the film with "spending limit reached"
        return format(max(self.left, Decimal(0)), "f")

    def charge(self, figure: Any) -> None:
        try:
            amount = Decimal(str(figure))
        except (InvalidOperation, ValueError):
            return
        if amount.is_finite() and amount >= 0:
            self.spent += amount
            if self.left is not None:
                self.left -= amount


def _json_object(text: str | None) -> dict[str, Any]:
    match = re.search(r"\{.*\}", text or "", flags=re.S)
    try:
        data = json.loads(match.group(0)) if match else None
    except ValueError:
        data = None
    if not isinstance(data, dict):
        raise StudioError("the reply was not JSON in the planned shape")
    return data


def load_facts(path: Path) -> dict[str, Any]:
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, ValueError):
        raise StudioError(f"fact sheet {path} is not valid JSON") from None
    if not isinstance(raw, dict):
        raise StudioError("fact sheet must be a JSON object")
    product = raw.get("product")
    if not isinstance(product, str) or not product.strip():
        raise StudioError("fact sheet needs a non-empty product")
    summary = raw.get("summary")
    if not isinstance(summary, str) or not summary.strip():
        raise StudioError("fact sheet needs a non-empty summary")
    facts_list = raw.get("facts", [])
    if facts_list is None:
        facts_list = []
    if not isinstance(facts_list, list) or any(not isinstance(item, str) for item in facts_list):
        raise StudioError("fact sheet facts must be a list of strings")
    commands: list[dict[str, Any]] = []
    for index, item in enumerate(raw.get("commands") or []):
        if not isinstance(item, dict):
            raise StudioError(f"fact sheet commands entry {index + 1} must be an object")
        cmd_id = item.get("id")
        if not isinstance(cmd_id, str) or not cmd_id.strip():
            raise StudioError(f"fact sheet commands entry {index + 1} needs a non-empty id")
        argv = item.get("argv")
        if not isinstance(argv, list) or not argv or any(not isinstance(part, str) or not part for part in argv):
            raise StudioError(f"fact sheet command {cmd_id!r} needs a non-empty argv list of strings")
        entry: dict[str, Any] = {"id": cmd_id.strip(), "argv": list(argv)}
        if "shows" in item and item["shows"] is not None:
            if not isinstance(item["shows"], str):
                raise StudioError(f"fact sheet command {cmd_id!r} shows must be a string")
            entry["shows"] = item["shows"]
        if item.get("display") is not None:
            if not isinstance(item["display"], str):
                raise StudioError(f"fact sheet command {cmd_id!r} display must be a string")
            entry["display"] = item["display"]
        if "cwd" in item and item["cwd"] is not None:
            if not isinstance(item["cwd"], str):
                raise StudioError(f"fact sheet command {cmd_id!r} cwd must be a string")
            entry["cwd"] = item["cwd"]
        commands.append(entry)
    pages: list[dict[str, Any]] = []
    for index, item in enumerate(raw.get("pages") or []):
        if not isinstance(item, dict):
            raise StudioError(f"fact sheet pages entry {index + 1} must be an object")
        page_id = item.get("id")
        if not isinstance(page_id, str) or not page_id.strip():
            raise StudioError(f"fact sheet pages entry {index + 1} needs a non-empty id")
        url = item.get("url")
        if not isinstance(url, str) or not url.strip():
            raise StudioError(f"fact sheet page {page_id!r} needs a url string")
        entry = {"id": page_id.strip(), "url": url.strip()}
        if "shows" in item and item["shows"] is not None:
            if not isinstance(item["shows"], str):
                raise StudioError(f"fact sheet page {page_id!r} shows must be a string")
            entry["shows"] = item["shows"]
        if item.get("steps") is not None:
            try:
                recording.check_steps(item["steps"])
            except capture.CaptureError as exc:
                raise StudioError(f"fact sheet page {page_id!r} steps: {exc}") from None
            entry["steps"] = list(item["steps"])
        size = item.get("size")
        if size is not None:
            if not (isinstance(size, list) and len(size) == 2
                    and all(isinstance(v, int) and not isinstance(v, bool) and 200 <= v <= 4000 for v in size)):
                raise StudioError(f"fact sheet page {page_id!r} size must be [width, height] in pixels, 200 to 4000")
            entry["size"] = list(size)
        if item.get("frame") is not None:
            if item["frame"] not in ("window", "phone"):
                raise StudioError(f"fact sheet page {page_id!r} frame must be window or phone")
            entry["frame"] = item["frame"]
        pages.append(entry)
    seen: set[str] = set()
    for item in commands + pages:
        if item["id"] in seen:
            raise StudioError(f"fact sheet id {item['id']!r} is used more than once")
        seen.add(item["id"])
    return {
        "product": product.strip(),
        "summary": summary.strip(),
        "facts": facts_list,
        "commands": commands,
        "pages": pages,
    }


def _facts_lookup(facts: dict[str, Any]) -> dict[str, dict[str, Any]]:
    lookup: dict[str, dict[str, Any]] = {}
    for item in facts.get("commands") or []:
        lookup[item["id"]] = {"kind": "command", **item}
    for item in facts.get("pages") or []:
        lookup[item["id"]] = {"kind": "page", **item}
    return lookup


def script_prompt(brief: str, seconds: int, facts: dict[str, Any] | None = None) -> str:
    if facts is None:
        return _SCRIPT.format(seconds=seconds, brief=brief, **script_budget(seconds))
    lines = [f"- {item['id']}: {item.get('shows', item['id'])} (a terminal: the command typed out, then its real "
             f"output)" for item in facts.get("commands") or []]
    lines += [f"- {item['id']}: {item.get('shows', item['id'])} (the page, recorded as it is used)"
              for item in facts.get("pages") or []]
    facts_block = "\n".join(f"- {line}" for line in facts.get("facts") or []) or "- (none listed)"
    return _SCRIPT_FACTS.format(
        seconds=seconds,
        brief=brief,
        **script_budget(seconds),
        product=facts["product"],
        summary=facts["summary"],
        facts_block=facts_block,
        capture_list="\n".join(lines) or "- (none)",
    )


def plan_from(data: dict[str, Any], seconds: int, facts: dict[str, Any] | None = None) -> tuple[str, str, str, list[Shot]]:
    lookup = _facts_lookup(facts) if facts else {}
    shots = []
    for raw in data.get("shots") or []:
        if not isinstance(raw, dict):
            continue
        source = str(raw.get("source", "generate")).strip() or "generate"
        try:
            length = max(1, min(20, int(round(float(raw.get("seconds", 4))))))
        except (TypeError, ValueError):
            length = 4
        caption = str(raw.get("caption", "")).strip()
        if source == "capture":
            if facts is None:
                raise StudioError("capture shots need a fact sheet (--facts)")
            ref = raw.get("ref")
            if not isinstance(ref, str) or not ref.strip():
                continue
            ref = ref.strip()
            item = lookup.get(ref)
            if item is None:
                raise StudioError(f"capture ref {ref!r} is not in the fact sheet")
            visual = str(raw.get("visual", "")).strip() or str(item.get("shows") or ref)
            shots.append(Shot(length, visual, caption, source="capture", ref=ref))
        elif source == "generate":
            if not str(raw.get("visual", "")).strip():
                continue
            shots.append(Shot(length, str(raw["visual"]).strip(), caption, source="generate"))
        else:
            if not str(raw.get("visual", "")).strip():
                continue
            shots.append(Shot(length, str(raw["visual"]).strip(), caption))
    if not shots:
        raise StudioError("the script has no shots")
    total = sum(s.seconds for s in shots)
    if seconds and abs(total - seconds) > max(2, seconds // 10):  # stretch or shrink to the asked length
        scale = seconds / total
        for shot in shots:
            shot.seconds = max(1, round(shot.seconds * scale))
        shots[-1].seconds = max(1, shots[-1].seconds + seconds - sum(s.seconds for s in shots))
    return str(data.get("title", "")).strip(), str(data.get("voiceover", "")).strip(), str(data.get("music", "")).strip(), shots


_PHRASE_N = re.compile(r"^(\s*phrase\s+)(\d+)")


def _local_phrases(item: Any, before: int, said: int) -> Any:
    """An overlay or sound timed to 'phrase N' counted across the whole film, read as its sentence in this beat: a
    writer that numbers every sentence of the film in one run means the same moment. A number this beat has is
    left as it is."""
    if not isinstance(item, dict):
        return item
    out = dict(item)
    for field in ("at", "until"):
        match = _PHRASE_N.match(out[field]) if isinstance(out.get(field), str) else None
        if match and int(match.group(2)) > said and 1 <= int(match.group(2)) - before <= said:
            out[field] = f"{match.group(1)}{int(match.group(2)) - before}{out[field][match.end():]}"
    return out


def _film_counts(rows: list[Any]) -> list[tuple[int, int]]:
    """For each beat: how many sentences the beats before it say, and how many it says itself."""
    counts, before = [], 0
    for raw in rows:
        say = raw.get("say") if isinstance(raw, dict) else None
        said = len(storyboard.split_phrases(say)) if isinstance(say, str) else 0
        counts.append((before, said))
        before += said
    return counts


_PHRASE_WHEN = re.compile(r"^\s*phrase\s+(\d+)(\s+end)?\s*$")


def _phrase_top(row: dict[str, Any], said: int) -> int:
    """The highest sentence a beat's overlays and sounds are timed to, counting the ones it says."""
    top = said
    for key in ("layers", "sounds"):
        items = row.get(key)
        for item in items if isinstance(items, list) else []:
            for field in ("at", "until"):
                value = item.get(field) if isinstance(item, dict) else None
                match = _PHRASE_WHEN.match(value) if isinstance(value, str) else None
                if match:
                    top = max(top, int(match.group(1)))
    return top


def _spread_phrases(item: Any, said: int, last_words: int, top: int) -> Any:
    """An overlay or sound timed to a sentence its beat does not say, read as a moment inside the beat's last
    sentence: a writer that times a one-sentence beat to 'phrase 2' and 'phrase 3' means later moments in it, so
    they are spread across that sentence in order instead of all playing at the default moment."""
    if not isinstance(item, dict) or said < 1:
        return item
    out = dict(item)
    spoken = max(last_words, 1) / SPEAKING_RATE
    for field in ("at", "until"):
        match = _PHRASE_WHEN.match(out[field]) if isinstance(out.get(field), str) else None
        if match and int(match.group(1)) > said:
            step = int(match.group(1)) - said + (1 if match.group(2) else 0)
            out[field] = f"phrase {said} + {round(spoken * step / (top - said + 1), 1)}"
    return out


def beats_from(data: dict[str, Any], facts: dict[str, Any] | None = None) -> list[dict[str, Any]]:
    """The storyboard rows from a model's beats plan, checked before anything is spent on them.

    A base with a prompt is generated, a base with a ref is real footage from the fact sheet, and a beat with
    neither stands on a moving background. Everything else is checked the way the storyboard and the motion
    graphics will read it, so a bad plan stops here, not after the pictures and the voice are paid for."""
    lookup = _facts_lookup(facts) if facts else {}
    rows = data.get("beats")
    if not isinstance(rows, list) or not rows:
        raise StudioError("the script has no beats")
    for number, raw in enumerate(rows, start=1):
        if not isinstance(raw, dict):
            raise StudioError(_not_a_beat(number, raw))
    out = []
    before = 0  # sentences in the beats before this one, to read a phrase counted across the whole film
    for number, raw in enumerate(rows, start=1):
        row = {k: v for k, v in raw.items() if k in ("say", "layers", "sounds", "cut", "energy", "hold")}
        if isinstance(row.get("say"), str) and not row["say"].strip():
            row["say"] = BLANK_LINE  # a line the writer left empty would be an empty caption: a full stop stands in
        said = len(storyboard.split_phrases(row["say"])) if isinstance(row.get("say"), str) else 0
        for key in ("layers", "sounds"):
            if isinstance(row.get(key), list):
                row[key] = [_local_phrases(item, before, said) for item in row[key]]
        before += said
        base = raw.get("base") or {}
        if not isinstance(base, dict):
            raise StudioError(f"beat {number}: base must be an object with a prompt or a ref")
        if isinstance(base.get("ref"), str) and base["ref"].strip():
            if base["ref"].strip() not in lookup:
                raise StudioError(f"beat {number}: footage ref {base['ref'].strip()!r} is not in the fact sheet")
            row["base"] = {"kind": "capture", "ref": base["ref"].strip()}
        elif isinstance(base.get("prompt"), str) and base["prompt"].strip():
            row["base"] = {"kind": "generate", "prompt": base["prompt"].strip()}
        else:
            row["base"] = {"kind": "living"}
        out.append(row)
    dry = [{**row, "base": {"kind": "living"}} for row in out]
    try:
        beats = storyboard.parse(dry, Path.cwd())
        for beat in beats:
            layers = [{**lay, "at": 0, **({"until": 1} if "until" in lay else {}),
                       **({"file": __file__} if lay.get("kind") in ("image", "video") and "file" not in lay
                          and isinstance(lay.get("prompt"), str) and lay["prompt"].strip() else {})}
                      for lay in beat.layers]
            motion.check_scene({"size": [64, 64], "seconds": 1, "layers": layers})
    except storyboard.StoryboardError as exc:
        raise StudioError(str(exc)) from exc
    except motion.MotionError as exc:
        raise StudioError(f"beat {beat.number}: {exc}") from exc
    return out


