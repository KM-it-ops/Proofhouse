def _numbers(text: str) -> set[str]:
    """The figures in ``text``, without version tags such as v1.0 and with thousands commas taken out."""
    return {n.replace(",", "") for n in _NUMBER.findall(text) if not n.lower().startswith("v")}


_SPELLED = {word: str(n) for n, word in enumerate(
    "zero one two three four five six seven eight nine ten eleven twelve thirteen fourteen fifteen sixteen "
    "seventeen eighteen nineteen twenty".split())}
_SPELLED.update({"thirty": "30", "forty": "40", "fifty": "50", "sixty": "60", "seventy": "70", "eighty": "80",
                 "ninety": "90", "hundred": "100", "thousand": "1000", "million": "1000000", "once": "1",
                 "twice": "2", "single": "1", "dozen": "12"})


def _spelled(text: str) -> set[str]:
    """The figures ``text`` spells out in words: 'one line' gives 1, 'twelve providers' gives 12."""
    return {_SPELLED[w] for w in re.findall(r"[a-z]+", text.lower()) if w in _SPELLED}


def _shown(value: Any, key: str = "") -> list[str]:
    """Every piece of text a layer puts on screen."""
    if key in _PLACING:
        return []
    if isinstance(value, dict):
        return [t for k, v in value.items() for t in _shown(v, k)]
    if isinstance(value, list):
        return [t for v in value for t in _shown(v)]
    if isinstance(value, bool):
        return []
    return [str(value)] if isinstance(value, (str, int, float)) else []


def _spoken(row: dict[str, Any]) -> str:
    say = row.get("say")
    if isinstance(say, list):
        return " ".join(s for s in say if isinstance(s, str))
    return say if isinstance(say, str) else ""


def usable_footage(facts: dict[str, Any] | None, allow_commands: bool) -> list[str]:
    """The fact sheet's footage ids this run can record: commands first when they may run, then pages."""
    if not facts:
        return []
    ids = [c["id"] for c in facts.get("commands") or []] if allow_commands else []
    return ids + [p["id"] for p in facts.get("pages") or []]


# Words too common to say what a line or a piece of footage is about.
_MATCH_STOP = {"the", "and", "a", "an", "of", "to", "in", "on", "for", "with", "from", "by", "or", "at", "as", "is",
               "are", "be", "it", "its", "it's", "you", "your", "we", "our", "they", "their", "this", "that", "these",
               "those", "can", "use", "used", "using", "any", "every", "each", "all", "one", "ones", "here", "there",
               "what", "which", "who", "how", "so", "too", "also", "just", "then", "than", "into", "out", "up", "not",
               "no", "yes", "list", "listed", "show", "shows", "shown", "see", "terminal", "screen", "page", "command",
               "output", "typed", "real", "now", "get", "got", "has", "have", "had", "does", "do", "did", "will"}


def _about(text: str, skip: set[str] = frozenset()) -> set[str]:
    """The words ``text`` is about, lower case and singular, so 'providers' meets 'provider'."""
    words = {w[:-1] if len(w) > 3 and w.endswith("s") and not w.endswith("ss") else w
             for w in re.findall(r"[a-z]+", text.lower()) if w not in _MATCH_STOP and len(w) > 2}
    return words - skip


def _footage_topics(facts: dict[str, Any] | None, footage: list[str]) -> dict[str, set[str]]:
    """Each piece of footage's subject words, from what the fact sheet says it shows and the command it types."""
    if not facts:
        return {}
    lookup = _facts_lookup(facts)
    skip = _about(str(facts.get("product", "")))
    topics = {}
    for ref in footage:
        item = lookup.get(ref)
        if item:
            words = _about(" ".join(str(item.get(k) or "") for k in ("shows", "display", "id")), skip)
            if words:
                topics[ref] = words
    return topics


def footage_moves(board: list[dict[str, Any]], facts: dict[str, Any] | None,
                  footage: list[str]) -> list[tuple[str, int, list[int]]]:
    """Where real footage belongs and is not yet: (footage id, the beat whose line it proves, the beats it is on now,
    empty when it is on none). Footage already under a line it proves as well as any stays; each beat holds one
    piece; footage that matches no line is left where it is; unused footage is placed only while real footage
    stays within a third of the beats."""
    topics = _footage_topics(facts, footage)
    said = [_about(_spoken(row)) for row in board]

    def score(number: int, ref: str) -> int:
        return len(topics[ref] & said[number - 1])

    numbers = range(1, len(board) + 1)
    best = {ref: max((score(n, ref) for n in numbers), default=0) for ref in topics}
    best = {ref: top for ref, top in best.items() if top >= 1}
    holding = {n: row["base"].get("ref") for n, row in enumerate(board, start=1) if row["base"].get("kind") == "capture"}
    placed: dict[str, int] = {}
    taken: set[int] = set()
    for n, ref in holding.items():
        if ref in best and ref not in placed and score(n, ref) == best[ref]:
            placed[ref] = n
            taken.add(n)
    order = sorted(((score(n, ref), n, footage.index(ref), ref) for ref in best for n in numbers),
                   key=lambda item: (-item[0], item[1], item[2]))
    for points, n, _, ref in order:
        if points >= 1 and ref not in placed and n not in taken:
            placed[ref] = n
            taken.add(n)
    room = max(1, len(board) // 3) - len(holding)
    moves = []
    for ref in sorted(placed, key=lambda r: (not any(h == r for h in holding.values()), placed[r])):
        now = [n for n, held in holding.items() if held == ref]
        if placed[ref] in now:
            continue
        if not now:
            if room <= 0:
                continue
            room -= 1
        moves.append((ref, placed[ref], now))
    return moves


def _line(board: list[dict[str, Any]], number: int) -> str:
    said = _spoken(board[number - 1]).strip()
    return repr(said if len(said) <= 60 else said[:57].rstrip() + "...")


PLAN_HEADING = "\n\nPLAN:\n"  # where a brief's plan starts: what a model wrote, never what the owner gave
DEFAULT_LOOK = "deep navy and teal palette with warm amber highlights, soft volumetric light, 35mm lens, shallow depth of field"
PICTURE_RULES = ("cinematic film look; no readable text, numbers, logos or brand names; no hooded hackers, glowing "
                 "padlocks or other stock-photo cliches")
# A figure a picture would draw: $50, 32.40, 12%, but not the 35 of "35mm" or the 1.8 of "f/1.8".
_PICTURE_FIGURE = re.compile(r"(?<![\w./])[$€£¥]?\d+(?:[.,]\d+)*%?(?!\w)")


def picture_prompt(prompt: str, look: str = "") -> str:
    """What a picture service is asked for: the beat's own prompt, the film's shared look and the rules every
    picture keeps, so the pictures read as one film and carry no made-up words or figures."""
    shared = look.strip().rstrip(".") or DEFAULT_LOOK
    return f"{prompt.strip().rstrip('.')}. Look: {shared}. {PICTURE_RULES}."


def _figure(text: str) -> str:
    return text.lstrip("$€£¥").rstrip("%").replace(",", "")


def _picture_figures(prompt: str) -> set[str]:
    return {_figure(n) for n in _PICTURE_FIGURE.findall(prompt)}


def _without_figures(prompt: str, figures: list[str]) -> str:
    """``prompt`` with ``figures`` (and their currency or percent signs) taken out."""
    out = _PICTURE_FIGURE.sub(lambda m: "" if _figure(m.group(0)) in figures else m.group(0), prompt)
    return re.sub(r"\s{2,}", " ", re.sub(r"\s+([,.;:])", r"\1", out)).strip()


def _invented(board: list[dict[str, Any]], brief: str,
              facts: dict[str, Any]) -> list[tuple[int, int | str | None, list[str]]]:
    """Figures the film shows or says that the brief and the fact sheet never give: (beat, layer, "picture" for
    its picture prompt or None for the narration, the figures). Only the owner's part of the brief counts: the plan
    a model wrote after it, and anything after that, gives no figure."""
    source = " ".join([brief.split(PLAN_HEADING, 1)[0], str(facts.get("product", "")), str(facts.get("summary", ""))]
                      + [str(f) for f in facts.get("facts") or []]
                      + [str(item.get(k, "")) for item in (facts.get("commands") or []) + (facts.get("pages") or [])
                         for k in ("shows", "display")])
    known = _numbers(source) | _spelled(source)
    # a counter counts up, so 'one command line tool' or 'one line' in the facts is no reason to count to 1 or 0:
    # that only flashes a stray digit on screen. Such a counter needs the figure written as a digit.
    counted = _numbers(source) | (_spelled(source) - {"0", "1"})
    found = []
    for number, row in enumerate(board, start=1):
        for index, layer in enumerate(row.get("layers") or [], start=1):
            given = counted if isinstance(layer, dict) and layer.get("kind") == "counter" else known
            new = sorted(_numbers(" ".join(_shown(layer))) - given)
            if new:
                found.append((number, index, new))
        new = sorted(_numbers(_spoken(row)) - known)
        if new:
            found.append((number, None, new))
        base = row.get("base") or {}
        if base.get("kind") == "generate":
            new = sorted(_picture_figures(str(base.get("prompt", ""))) - known)
            if new:
                found.append((number, "picture", new))
    return found


def _words(board: list[dict[str, Any]]) -> int:
    return sum(len(_spoken(row).split()) for row in board)


def narration_aim(seconds: float) -> int:
    """Words the engine grows thin narration to: nine tenths of what the film can hold, so the voice fills it
    without long silences and still leaves room for the joins."""
    return script_budget(seconds)["words"] * 9 // 10


# words that make narration sound like an advert rather than a person talking
HYPE_WORDS = ("unlock", "unleash", "seamless", "seamlessly", "effortless", "effortlessly", "instantly", "materialize",
              "materializes", "possibilities", "limitless", "infinite", "revolutionize", "revolutionary",
              "game-changer", "game-changing", "supercharge", "next-level", "cutting-edge", "empower", "elevate")
# a sentence that tells the viewer the film's own rules, which only the writer needed to hear
_RULE_ECHO = re.compile(r"\b(?:made[- ]up|invented|fake)\s+(?:stats|statistics|numbers|figures|claims)\b|"
                        r"\bverified\s+facts\b|\bno\s+invented\b", re.IGNORECASE)


def narration_slips(board: list[dict[str, Any]]) -> list[tuple[int, list[str], list[str]]]:
    """Beats (numbered from 1) whose narration sounds like an advert or repeats the film's own rules: each with
    the advert words it uses and the sentences that echo the rules."""
    found = []
    for number, row in enumerate(board, start=1):
        say = row.get("say") if isinstance(row.get("say"), str) else ""
        words = sorted({w for w in re.findall(r"[a-z]+(?:-[a-z]+)*", say.lower()) if w in HYPE_WORDS})
        echoes = [s for s in storyboard.split_phrases(say) if _RULE_ECHO.search(s)] if say else []
        if words or echoes:
            found.append((number, words, echoes))
    return found


def narration_thin(board: list[dict[str, Any]], seconds: float, voiced: bool) -> bool:
    """True when a voiced film says fewer words than the script was asked for at least, so it would sit in silence."""
    words = _words(board)
    return voiced and bool(words) and words < script_budget(seconds)["least"]


_PHRASE_AT = re.compile(r"^\s*phrase\s+(\d+)")


def split_beats(board: list[dict[str, Any]], fewest: int) -> int:
    """Too few beats for the film: the beat with the most sentences gives its last sentence a shot of its own, the
    same picture seen closer from another angle, until the film has ``fewest`` beats or no beat has two sentences.
    Real footage is never split. Overlays and sounds stay on the first part, and any timed to a sentence that moved
    land at the end of its last one. Returns how many beats were added."""
    added = 0
    while len(board) < fewest:
        counts = {i: len(storyboard.split_phrases(_spoken(row))) for i, row in enumerate(board)
                  if row["base"]["kind"] != "capture" and isinstance(row.get("say"), str)}
        pick = max((i for i, n in counts.items() if n > 1), key=lambda i: counts[i], default=None)
        if pick is None:
            break
        row = board[pick]
        said = storyboard.split_phrases(row["say"])
        kept = len(said) - 1
        row["say"] = " ".join(said[:kept])
        for key in ("layers", "sounds"):
            for item in row.get(key) or []:
                for field in ("at", "until"):
                    match = _PHRASE_AT.match(str(item.get(field, ""))) if isinstance(item, dict) else None
                    if match and int(match.group(1)) > kept:
                        item[field] = f"phrase {kept} end"
        base = dict(row["base"])
        if base["kind"] == "generate":
            base["prompt"] = f"{base['prompt'].rstrip('.')}, seen closer from another angle"
        new = {"say": said[-1], "base": base}
        if row.get("energy"):
            new["energy"] = row["energy"]
        board.insert(pick + 1, new)
        added += 1
    return added


# where a long sentence can be cut in two, the strongest pause first: a dash, colon or semicolon ends a thought;
# a comma before a joining word starts a new one; a plain comma or a joining word is a lighter pause
_CLAUSE_BREAKS = (re.compile(r"\s*[;:\u2014\u2013]\s+|\s+-\s+"),
                  re.compile(r",\s+(?=(?:and|but|so|while|then|yet)\b)", re.IGNORECASE),
                  re.compile(r",\s+"),
                  re.compile(r"\s+(?=(?:and|but|so|while|then)\b)", re.IGNORECASE))
CLAUSE_WORDS = 4  # the fewest words either half of a split sentence keeps, so each still says something


def clause_split(sentence: str) -> tuple[str, str] | None:
    """A long sentence cut in two at its strongest pause nearest the middle, each half a sentence of its own, or
    None when no pause leaves ``CLAUSE_WORDS`` words on both sides."""
    text = sentence.strip()
    middle = len(text.split()) / 2
    for breaks in _CLAUSE_BREAKS:
        cuts = []
        for found in breaks.finditer(text):
            head, tail = text[:found.start()].strip(), text[found.end():].strip()
            if len(head.split()) >= CLAUSE_WORDS and len(tail.split()) >= CLAUSE_WORDS:
                cuts.append((abs(len(head.split()) - middle), head, tail))
        if cuts:
            _, head, tail = min(cuts)
            return head.rstrip(",;:-\u2014\u2013 ") + ".", tail[0].upper() + tail[1:]
    return None


def split_clauses(board: list[dict[str, Any]], fewest: int) -> int:
    """Still too few beats once every beat says one sentence: the longest sentence that has a natural pause is cut
    there, and its second half gets a shot of its own, until the film has ``fewest`` beats or no sentence can be
    cut. Real footage is never split. Returns how many beats were added."""
    added, tried = 0, set()
    while len(board) < fewest:
        open_ = [(len(row["say"].split()), i) for i, row in enumerate(board)
                 if row["base"]["kind"] != "capture" and isinstance(row.get("say"), str) and i not in tried
                 and len(storyboard.split_phrases(row["say"])) == 1]
        if not open_:
            break
        _, pick = max(open_)
        halves = clause_split(board[pick]["say"])
        if halves is None:
            tried.add(pick)
            continue
        row = board[pick]
        row["say"] = halves[0]
        base = dict(row["base"])
        if base["kind"] == "generate":
            base["prompt"] = f"{base['prompt'].rstrip('.')}, seen closer from another angle"
        new = {"say": halves[1], "base": base}
        if row.get("energy"):
            new["energy"] = row["energy"]
        board.insert(pick + 1, new)
        tried = {i + 1 if i > pick else i for i in tried}
        added += 1
    return added


def _bare(board: list[dict[str, Any]]) -> list[int]:
    """Beats (numbered from 1) that stand on a plain moving background: no picture and no footage behind them."""
    return [n for n, row in enumerate(board, start=1) if row["base"]["kind"] == "living"]


def bare_allowed(board: list[dict[str, Any]]) -> int:
    """How many beats may stand on a plain background in a film with pictures: a quarter of them, as the
    reference films do, so most of the film has something real to look at."""
    return len(board) // 4


def picture_bare(board: list[dict[str, Any]]) -> list[int]:
    """Give the plain-background beats past a quarter of the film a picture of their own, the emptiest first: the
    nearest picture in the film seen from another angle, so it stays one world, or a scene for its words when the
    film has no picture yet. Returns the beats that got one."""
    bare = [n for n in _bare(board)
            if not any(isinstance(lay, dict) and lay.get("kind") == "terminal" for lay in board[n - 1].get("layers") or [])]
    extra = len(_bare(board)) - bare_allowed(board)
    picked = sorted(sorted(bare, key=lambda n: len(board[n - 1].get("layers") or []))[:max(0, extra)])
    for number in picked:
        near = sorted((abs(n - number), n) for n, row in enumerate(board, start=1)
                      if row["base"]["kind"] == "generate" and n not in picked)
        if near:
            prompt = f"{board[near[0][1] - 1]['base']['prompt'].rstrip('.')}, seen from another angle"
        else:
            words = _spoken(board[number - 1]).strip() or brief_line(board)
            prompt = f"a scene that shows what these words describe: {words}"
        board[number - 1]["base"] = {"kind": "generate", "prompt": prompt}
    return picked


def brief_line(board: list[dict[str, Any]]) -> str:
    """The film's first words, for a picture with nothing else to go on."""
    return next((_spoken(row).strip() for row in board if _spoken(row).strip()), "the subject of the film")


def scene_for(board: list[dict[str, Any]], number: int, framing: str = "") -> str:
    """A picture prompt for beat ``number`` (from 1) drawn from its own words, so it shows what is being said."""
    said = _spoken(board[number - 1]).strip() or brief_line(board)
    return f"{framing}, at the moment this describes: {said}" if framing else f"a scene that shows what this describes: {said}"


# Words in a picture prompt that ask the picture model to draw lettering, which it renders as made-up text.
_PICTURE_TEXT = re.compile(r"\b(?:text|texts|words?|messages?|labels?|label(?:l)?ed|captions?|titles?|logos?|headlines?|"
                           r"letters|lettering|typography|slogans?|banners?|signage|signs?|logs?|outputs?|commands?|"
                           r"code|readouts?|numbers|digits)\b|[\"“][^\"”]+[\"”]", re.I)
# Things a picture model fills with made-up writing whenever a picture is of them, whatever the prompt says is on them.
_SCREENS = {"screen", "screens", "terminal", "terminals", "console", "consoles", "monitor", "monitors", "display",
            "displays", "dashboard", "dashboards", "interface", "interfaces", "ui", "timeline", "timelines", "log",
            "logs", "desktop", "laptop", "laptops", "tablet", "tablets", "phone", "smartphone", "spreadsheet", "editor",
            "ide", "app", "readout"}
_NEGATED = re.compile(r"\b(?:no|without|free of)\b[^,.;]*", re.I)
_TEXT_LEAD = re.compile(r"\s+(?:with|showing|displaying|where|while|and|as|reading|saying|that says|that reads)\s",
                        re.I)


def _asks_text(prompt: str) -> list[str]:
    """The lettering a picture prompt asks for (its words, lowercased), leaving out what it says to avoid."""
    found = (m.group(0) for m in _PICTURE_TEXT.finditer(_NEGATED.sub("", prompt)))
    return sorted({"quoted words" if word[0] in "\"“" else word.lower() for word in found})


def screen_shown(prompt: str) -> str:
    """The screen a picture prompt is of ("terminal" for "a terminal screen showing a log"), or "" when it is of
    something else; a face lit by a screen's glow is of the face."""
    return next((word for word in _subject_words(prompt) if word in _SCREENS), "")


def text_asks(board: list[dict[str, Any]]) -> list[tuple[int, list[str]]]:
    """The beats (from 1) whose picture prompt asks for lettering, or is of a screen, with what it asks for."""
    found = []
    for n, row in enumerate(board, start=1):
        if row["base"]["kind"] == "generate":
            prompt = str(row["base"].get("prompt", ""))
            screen = screen_shown(prompt)
            asked = ([f"a {screen}"] if screen else []) + _asks_text(prompt)
            if asked:
                found.append((n, asked))
    return found


def _without_text(prompt: str) -> str:
    """``prompt`` with each part that asks for lettering cut back to what comes before it ("a terminal screen with a
    success message" becomes "a terminal screen"); parts that are only lettering are left out."""
    kept = []
    for part in re.split(r"[,;]", prompt):
        hit = _PICTURE_TEXT.search(_NEGATED.sub(lambda m: " " * len(m.group(0)), part))
        if hit is None:
            kept.append(part.strip())
            continue
        leads = [m.start() for m in _TEXT_LEAD.finditer(part[:hit.start()])]
        if leads and part[:leads[-1]].strip():
            kept.append(part[:leads[-1]].strip())
    return ", ".join(p for p in kept if p)


_SUBJECT_STOP = {"showing", "with", "of", "in", "on", "at", "displaying", "where", "that", "and", "while", "as",
                 "from", "under", "over", "behind", "filled", "full", "lit", "glowing", "seen", "for", "into", "to",
                 "by", "near", "against", "beside", "around"}
_SUBJECT_LEAD = {"a", "an", "the", "one", "single", "close-up", "closeup", "close", "up", "wide", "shot", "of",
                 "extreme", "medium", "view", "cinematic", "photo", "image", "picture"}


def _subject_words(prompt: str) -> list[str]:
    """The words naming what a picture prompt shows: "dark terminal screen" for "a dark terminal screen showing a
    command"."""
    words = re.findall(r"[a-z][a-z'-]*", prompt.lower().split(",")[0])
    while words and words[0] in _SUBJECT_LEAD:
        words.pop(0)
    out: list[str] = []
    for word in words:
        if out and word in _SUBJECT_STOP:  # a first word such as "glowing" describes the thing; it does not end it
            break
        out.append(word)
    return out


def picture_subject(prompt: str) -> str:
    """The thing a picture prompt shows, as its head word: "screen" for "a dark terminal screen showing a command",
    so a film whose every picture is the same thing can be told apart from one with varied scenes."""
    out = _subject_words(prompt)
    return out[-1] if out else ""


# The kinds of scene a film with every picture on one subject is told to use, and the engine uses when it must vary
# the pictures itself: people, places, close and wide, all in the film's one look, none facing a screen's writing.
SCENE_FRAMINGS = ("a person at work, seen from the side", "a close-up of hands at work",
                  "a wide shot of the room where the work happens", "a face lit by the glow of a screen",
                  "a city at night seen through a window", "a team around a table, seen from across the room")


def same_subject(board: list[dict[str, Any]]) -> tuple[str, list[int]] | None:
    """The subject most of a film's pictures share, and their beats (from 1), when more pictures show it than a
    film with varied scenes would: a third of its pictures, and at least two. None when the pictures vary."""
    prompts = {n: picture_subject(str(row["base"].get("prompt", ""))) for n, row in enumerate(board, start=1)
               if row["base"]["kind"] == "generate"}
    counts: dict[str, list[int]] = {}
    for number, subject in prompts.items():
        if subject:
            counts.setdefault(subject, []).append(number)
    if not counts:
        return None
    subject, beats = max(counts.items(), key=lambda item: len(item[1]))
    return (subject, beats) if len(prompts) >= 3 and len(beats) > subject_allowed(len(prompts)) else None


def subject_allowed(pictures: int) -> int:
    """How many of a film's pictures may show the same subject: a third of them, and at least two."""
    return max(2, pictures // 3)


def vary_pictures(board: list[dict[str, Any]]) -> list[int]:
    """Past a third of a film's pictures on one subject, the rest show a scene of their own: a person, a place, a
    close-up or a wide shot, in turn, for what that beat says. Returns the beats that changed."""
    found = same_subject(board)
    if found is None:
        return []
    _, beats = found
    keep = subject_allowed(sum(row["base"]["kind"] == "generate" for row in board))
    # the writer's own prompts are kept before the engine's copies of them ("..., seen from another angle")
    copied = {n for n in beats if "another angle" in str(board[n - 1]["base"].get("prompt", ""))}
    changed = sorted(sorted(beats, key=lambda n: (n in copied, n))[keep:])
    for turn, number in enumerate(changed):
        board[number - 1]["base"] = {"kind": "generate",
                                     "prompt": scene_for(board, number, SCENE_FRAMINGS[turn % len(SCENE_FRAMINGS)])}
    return changed


def script_gaps(board: list[dict[str, Any]], *, brief: str, seconds: float, facts: dict[str, Any] | None,
                footage: list[str], voiced: bool, pictures: bool = False) -> list[str]:
    """What a readable storyboard still lacks to make a good film, each said so the writer can fix it: no real
    footage when the fact sheet has some, figures nobody gave it, too few beats, narration too thin to fill it."""
    gaps = []
    moves = footage_moves(board, facts, footage)
    if footage and not moves and not any(row["base"]["kind"] == "capture" for row in board):
        gaps.append(f"the film shows no real product footage: make at least one beat's base {{\"ref\": \"<id>\"}} "
                    f"using one of: {', '.join(footage)}")
    for ref, number, now in moves:
        if now:
            gaps.append(f"beat{'s' if len(now) > 1 else ''} {', '.join(map(str, now))} show{'' if len(now) > 1 else 's'} "
                        f"the footage {ref!r}, which proves what beat {number} says ({_line(board, number)}): move it "
                        f"there, under the line it shows, and give the other beat a picture of its own words")
        else:
            gaps.append(f"the footage {ref!r} shows what beat {number} says ({_line(board, number)}) but is never "
                        f"used: make that beat's base {{\"ref\": \"{ref}\"}}")
    if facts:
        for number, layer, new in _invented(board, brief, facts):
            if layer == "picture":
                gaps.append(f"beat {number}'s picture prompt asks for {', '.join(new)}, which the brief and facts "
                            f"never give: describe the scene with no figures, because a picture model draws them as "
                            f"made-up text")
                continue
            where = f"beat {number} layer {layer}" if layer else f"beat {number}'s narration"
            gaps.append(f"{where} states {', '.join(new)}, which the brief and facts never give: say only what they "
                        f"say, with no invented numbers, timings or results")
    if pictures:
        for number, asked in text_asks(board):
            screen = (" and fills any screen with them, so show the people, hands and places around the work "
                      "instead of a screen") if screen_shown(str(board[number - 1]["base"].get("prompt", ""))) else ""
            gaps.append(f"beat {number}'s picture prompt asks for {', '.join(asked)}: describe a scene with no "
                        f"writing in it, because a picture model draws words as made-up text{screen}")
    for number, words, echoes in narration_slips(board):
        if words:
            gaps.append(f"beat {number}'s narration says {', '.join(words)}, which sounds like an advert, not a person: "
                        f"say what it does in plain, concrete words")
        for said in echoes:
            gaps.append(f"beat {number}'s narration {said!r} tells the viewer the film's own rules, which only you "
                        f"needed: say what the product does instead")
    fit = script_budget(seconds)
    if len(board) < fit["fewest"]:
        gaps.append(f"the film has only {len(board)} beats, and {seconds} seconds needs {fit['fewest']} to "
                    f"{fit['most']}, so something new is on screen every few seconds: split long beats and add beats, "
                    f"each with its own picture")
    if pictures and len(_bare(board)) > bare_allowed(board):
        gaps.append(f"beats {', '.join(map(str, _bare(board)))} have no picture and stand on a plain background, "
                    f"which looks empty: give most of them a base prompt, so {bare_allowed(board) or 'no'} beats at "
                    f"most have no picture")
    same = same_subject(board) if pictures else None
    if same:
        gaps.append(f"beats {', '.join(map(str, same[1]))} all picture a {same[0]}, so the film shows one thing over "
                    f"and over: give each beat its own scene from the same world and look, such as people at work, "
                    f"the places they work in, close-ups of hands and faces, and wide shots")
    if narration_thin(board, seconds, voiced):
        gaps.append(f"the narration is too thin: {_words(board)} words over {seconds} seconds leaves long silences; "
                    f"use {fit['least']} to {fit['words']} words in full flowing sentences")
    return gaps


def settle_gaps(board: list[dict[str, Any]], *, brief: str, seconds: float, facts: dict[str, Any] | None,
                footage: list[str], voiced: bool, pictures: bool = False) -> list[str]:
    """With no fixes left, the engine settles what ``script_gaps`` found itself, and says what it did: the middle
    beat shows real footage, overlays with invented figures are left out and picture prompts lose them, beats with
    several sentences are split until the film has enough shots, and thin narration is noted."""
    notes = []
    moves = footage_moves(board, facts, footage)
    left = {n for _, _, now in moves for n in now} - {number for _, number, _ in moves}
    for ref, number, now in moves:
        board[number - 1]["base"] = {"kind": "capture", "ref": ref}
        moved = f", moved from beat{'s' if len(now) > 1 else ''} {', '.join(map(str, now))}" if now else ""
        notes.append(f"beat {number} shows the real footage {ref!r}, under the line it proves{moved}")
    for number in sorted(left):
        board[number - 1]["base"] = ({"kind": "generate", "prompt": scene_for(board, number)} if pictures
                                     else {"kind": "living"})
    if footage and not any(row["base"]["kind"] == "capture" for row in board):
        middle = len(board) // 2
        board[middle]["base"] = {"kind": "capture", "ref": footage[0]}
        notes.append(f"beat {middle + 1} shows the real footage {footage[0]!r}")
    if facts:
        found = _invented(board, brief, facts)
        drop = {(number, layer) for number, layer, _ in found if isinstance(layer, int)}
        for number, layer, new in found:
            if layer == "picture":
                base = board[number - 1]["base"]
                base["prompt"] = _without_figures(base["prompt"], new)
                notes.append(f"beat {number}'s picture prompt no longer asks for {', '.join(new)}, which the facts "
                             f"never give")
            elif layer:
                notes.append(f"beat {number} layer {layer} left out: it showed {', '.join(new)}, which the facts "
                             f"never give")
            else:
                notes.append(f"beat {number}'s narration says {', '.join(new)}, which the facts never give")
        for number, row in enumerate(board, start=1):
            if row.get("layers"):
                row["layers"] = [lay for i, lay in enumerate(row["layers"], start=1) if (number, i) not in drop]
    if pictures:
        for turn, (number, asked) in enumerate(text_asks(board)):
            base = board[number - 1]["base"]
            if screen_shown(base["prompt"]):  # whatever is left of a screen, the picture model writes on it
                base["prompt"] = scene_for(board, number, SCENE_FRAMINGS[turn % len(SCENE_FRAMINGS)])
            else:
                base["prompt"] = _without_text(base["prompt"]) or scene_for(board, number)
            notes.append(f"beat {number}'s picture prompt no longer asks for {', '.join(asked)}, which a picture "
                         f"model draws as made-up text")
    for number, words, echoes in narration_slips(board):
        row = board[number - 1]
        if echoes:  # a sentence about the rules says nothing to the viewer, so it goes
            kept = [s for s in storyboard.split_phrases(row["say"]) if s not in echoes]
            if kept:
                row["say"] = " ".join(kept)
            else:
                row.pop("say")
            notes.append(f"beat {number} no longer says {', '.join(map(repr, echoes))}, which told the viewer the "
                         f"film's own rules")
        if words:
            notes.append(f"beat {number}'s narration still says {', '.join(words)}")
    fit = script_budget(seconds)
    if len(board) < fit["fewest"]:
        before = len(board)
        if split_beats(board, fit["fewest"]):
            notes.append(f"beats with several sentences were split so each sentence has its own shot: {before} beats "
                         f"became {len(board)}")
        if len(board) < fit["fewest"]:
            split = len(board)
            if split_clauses(board, fit["fewest"]):
                notes.append(f"long sentences were split at a natural pause so each half has its own shot: {split} "
                             f"beats became {len(board)}")
        if len(board) < fit["fewest"]:
            notes.append(f"the film stays at {len(board)} beats, fewer than the {fit['fewest']} {seconds} seconds needs")
    if pictures and len(_bare(board)) > bare_allowed(board):
        given = picture_bare(board)
        if given:
            notes.append(f"beats {', '.join(map(str, given))} had no picture, so each now shows one in the film's look")
    if pictures:
        same = same_subject(board)
        varied = vary_pictures(board)
        if varied and same:
            notes.append(f"beats {', '.join(map(str, varied))} pictured a {same[0]} like the rest, so each now shows "
                         f"a scene of its own in the film's look")
    if narration_thin(board, seconds, voiced):
        notes.append(f"the narration stays thin: {_words(board)} words over {seconds} seconds")
    return notes


def _not_a_beat(number: int, raw: Any) -> str:
    return (f"beat {number}: {json.dumps(raw)[:60]} is not a beat; each beat is one {{...}} object with its own "
            f"say and base, and nothing else belongs in the beats list")


def script_problems(data: dict[str, Any], facts: dict[str, Any] | None = None) -> list[str]:
    """Every problem in a beats plan, each named by its beat and layer or sound, so one fix can mend them all.

    The check that runs before anything is spent stops at the first problem; a script writer told only that one
    mends it and trips on the next, so this checks each beat, and each overlay and sound in it, on its own."""
    rows = data.get("beats")
    if not isinstance(rows, list) or not rows:
        return []
    found: list[str] = []
    counts = _film_counts(rows)
    for number, raw in enumerate(rows, start=1):
        if not isinstance(raw, dict):
            found.append(_not_a_beat(number, raw))
            continue
        before, said = counts[number - 1]
        bare = {k: v for k, v in raw.items() if k not in ("layers", "sounds")}
        try:
            beats_from({"beats": [bare]}, facts)
        except StudioError as exc:
            found.append(re.sub(r"^beat \d+:", f"beat {number}:", str(exc)))
            continue
        for key in ("layers", "sounds"):
            items = raw.get(key)
            if items is None:
                continue
            if not isinstance(items, list):
                try:
                    beats_from({"beats": [{**bare, key: items}]}, facts)
                except StudioError as exc:
                    found.append(re.sub(r"^beat \d+:", f"beat {number}:", str(exc)))
                continue
            for i, item in enumerate(items, start=1):
                try:  # a phrase counted across the whole film is read in its beat, as the film itself reads it
                    beats_from({"beats": [{**bare, key: [_local_phrases(item, before, said)]}]}, facts)
                except StudioError as exc:
                    told = re.sub(r"^(layer|sound)s?( \d+)?:? ?", "", re.sub(r"^beat \d+: ", "", str(exc)))
                    if "there is no phrase" in told:
                        told += (f": phrase N counts only this beat's own sentences, and its say has {said}, so time "
                                 f"a later moment as 'phrase {max(said, 1)} + seconds' or 'end'")
                    found.append(f"beat {number}: {key[:-1]} {i} {told}")
    return found


def untime_unreadable(data: dict[str, Any], facts: dict[str, Any] | None = None) -> tuple[dict[str, Any], list[str]]:
    """The beats plan with each overlay or sound time, and each beat's pace (its energy or cut), that cannot be
    read taken out, and a note for each.

    Used only once the script writer has had all its chances to fix them, so one garbled time or pace never costs
    the whole film: the overlay or sound plays at its default moment and the beat at its default pace, and a scrap
    of text left in the beats list by a broken reply is left out, and so is an overlay or sound the engine cannot draw
    (an unknown kind, a missing field), and so is a footage ref the fact sheet does not have, so a slip in one
    overlay or ref never costs the whole film; the engine's own extras
    fill a beat left bare. A broken beat itself is left as it is, so it stays a failure."""
    rows = data.get("beats")
    if not isinstance(rows, list):
        return data, []
    dropped: list[str] = []
    out: list[Any] = []
    if not any(isinstance(raw, dict) for raw in rows):
        return data, []
    counts = _film_counts(rows)
    for number, raw in enumerate(rows, start=1):
        if not isinstance(raw, dict):
            if not isinstance(raw, str):
                return data, []  # not a scrap of a broken reply
            dropped.append(f"beat {number} stray text {raw[:40]!r}")
            continue
        bare = {k: v for k, v in raw.items() if k not in ("layers", "sounds")}
        row = dict(raw)
        base = raw.get("base")
        if isinstance(base, dict) and isinstance(base.get("ref"), str) and base["ref"].strip() and \
                base["ref"].strip() not in (_facts_lookup(facts) if facts else {}):
            # footage that is not on the fact sheet cannot be recorded: the beat stands on what else its base gives
            dropped.append(f"beat {number} footage ref {base['ref'].strip()[:40]!r} (not in the fact sheet)")
            bare["base"] = row["base"] = {k: v for k, v in base.items() if k != "ref"}
        for pace in ("energy", "cut"):
            if pace in bare:
                try:
                    beats_from({"beats": [{"say": "x", "base": {"prompt": "x"}, pace: bare[pace]}]}, facts)
                except StudioError:
                    dropped.append(f"beat {number} {pace} {bare.pop(pace)!r}")
                    row.pop(pace)
        try:
            beats_from({"beats": [bare]}, facts)
        except StudioError:
            return data, []
        before, said = counts[number - 1]
        sentences = storyboard.split_phrases(raw["say"]) if isinstance(raw.get("say"), str) else []
        last_words = len(sentences[-1].split()) if sentences else 0
        top = _phrase_top(raw, said)
        for key in ("layers", "sounds"):
            if not isinstance(raw.get(key), list):
                continue
            keep = []
            for i, item in enumerate(raw[key], start=1):
                try:  # the film reads a phrase counted across the whole film as that sentence in its beat
                    beats_from({"beats": [{**bare, key: [_local_phrases(item, before, said)]}]}, facts)
                except StudioError:
                    spread = _spread_phrases(item, said, last_words, top)
                    try:
                        beats_from({"beats": [{**bare, key: [spread]}]}, facts)
                    except StudioError:
                        pass
                    else:
                        times = ", ".join(f"{item[k]!r} as {spread[k]!r}" for k in ("at", "until")
                                          if k in item and spread[k] != item[k])
                        dropped.append(f"beat {number} {key[:-1]} {i} time {times}")
                        keep.append(spread)
                        continue
                    plain = {k: v for k, v in item.items() if k not in ("at", "until")} if isinstance(item, dict) else item
                    try:
                        beats_from({"beats": [{**bare, key: [plain]}]}, facts)
                    except StudioError:  # not its time: the engine cannot draw it at all
                        kind = item.get("kind") if isinstance(item, dict) else None
                        dropped.append(f"beat {number} {key[:-1]} {i} ({kind or 'no kind'}) left out")
                        continue
                    times = ", ".join(repr(item[k]) for k in ("at", "until") if k in item)
                    dropped.append(f"beat {number} {key[:-1]} {i} time {times}")
                    item = plain
                keep.append(item)
            row[key] = keep
        out.append(row)
    return {**data, "beats": out}, dropped


def srt(shots: list[Shot]) -> str:
    def stamp(t: int) -> str:
        return f"{t // 3600:02d}:{t // 60 % 60:02d}:{t % 60:02d},000"

    blocks, start = [], 0
    for index, shot in enumerate(shots, start=1):
        if shot.caption:
            blocks.append(f"{index}\n{stamp(start)} --> {stamp(start + shot.seconds)}\n{shot.caption}\n")
        start += shot.seconds
    return "\n".join(blocks)


IMAGE_ZOOM = 0.12
STILL_ZOOM = 0.10
STILL_FIT = 1 / (1 + STILL_ZOOM)  # a capture is shown this big, so the camera at its closest still has all of it in view
MAX_HOLD = 3.0  # a picture that stays frozen this long (seconds) is a slideshow, not a film
# Something happens: a patch of the picture (1/40 by 1/22 of the frame) changes sharply between two looks 0.1 s apart,
# as when a title lands, a cut lands or a hand moves. A slow camera drift over a still never counts.
EVENT_LEVEL = 16  # mean brightness change of one patch, 0-255, that counts as something happening
MAX_QUIET = 3.0  # seconds a film may go with nothing happening
MIN_LIVELY = 0.85  # share of the film's one-second windows in which something happens

# how the camera moves on a capture: (zooms in?, sideways lean 0..1, vertical lean 0..1); neighbouring shots differ
_CAMERA_MOVES = ((True, 0.5, 0.5), (False, 0.5, 0.5), (True, 0.0, 0.3), (False, 1.0, 0.7))


def _eased_zoom(extra: float, frames: int, closer: bool) -> str:
    """Zoom between 1 and 1+extra over the whole shot, easing in and out so the move never stops short."""
    last = max(1, frames - 1)
    sign = "-" if closer else "+"
    return f"1+{extra}*(0.5{sign}0.5*cos(PI*on/{last}))"


def shot_command(source: Path, kind: str, seconds: float, size: tuple[int, int], out: Path, variant: int = 0) -> list[str]:
    """Cut one shot to length. Stills and images get a camera move that lasts the whole shot (`variant` picks which)."""
    w, h = size
    frames = round(seconds * FPS)
    head = ["ffmpeg", "-y", "-loglevel", "error"]
    tail = ["-c:v", "libx264", "-preset", "veryfast", "-an", str(out)]
    if kind == "still":
        # A real capture is never cropped. It sits on a soft, darkened copy of itself that fills the frame, and the
        # camera moves over that: in, out, or drifting to a side, always keeping the whole capture in view.
        closer, lean_x, lean_y = _CAMERA_MOVES[variant % len(_CAMERA_MOVES)]
        fit_w, fit_h = int(2 * w * STILL_FIT) // 2 * 2, int(2 * h * STILL_FIT) // 2 * 2
        small_w, small_h = max(2, w // 8 * 2), max(2, h // 8 * 2)
        total = f"(1+{STILL_ZOOM})"
        # the window may lean toward a side only as far as it still holds the whole capture
        def lean(size_name: str, window: str, lean_by: float) -> str:
            fg = f"({size_name}/{total})"
            lo = f"max(0,({size_name}-{fg})/2+{fg}-{window})"
            hi = f"min(({size_name}-{fg})/2,{size_name}-{window})"
            return f"{lo}+{lean_by}*({hi}-({lo}))"
        graph = (f"[0:v]split=2[bg][fg];"
                 f"[bg]scale={small_w}:{small_h}:force_original_aspect_ratio=increase,crop={small_w}:{small_h},boxblur=6:2,"
                 f"scale={2 * w}:{2 * h},eq=brightness=-0.28:saturation=0.85[back];"
                 f"[fg]scale={fit_w}:{fit_h}:force_original_aspect_ratio=decrease[front];"
                 f"[back][front]overlay=(W-w)/2:(H-h)/2,format=rgb24,"
                 f"zoompan=z='{_eased_zoom(STILL_ZOOM, frames, closer)}':x='{lean('iw', 'iw/zoom', lean_x)}':"
                 f"y='{lean('ih', 'ih/zoom', lean_y)}':d={frames}:s={w}x{h}:fps={FPS},format=yuv420p[v]")
        return head + ["-i", str(source), "-filter_complex", graph, "-map", "[v]", "-frames:v", str(frames)] + tail
    if kind == "image":
        vf = (f"scale={2 * w}:{2 * h}:force_original_aspect_ratio=increase,crop={2 * w}:{2 * h},"
              f"zoompan=z='{_eased_zoom(IMAGE_ZOOM, frames, variant % 2 == 0)}':x='iw/2-(iw/zoom/2)':y='ih/2-(ih/zoom/2)':"
              f"d={frames}:s={w}x{h}:fps={FPS},format=yuv420p")
        return head + ["-i", str(source), "-vf", vf, "-frames:v", str(frames)] + tail
    vf = f"scale={w}:{h}:force_original_aspect_ratio=increase,crop={w}:{h},fps={FPS},format=yuv420p"
    return ["ffmpeg", "-y", "-loglevel", "error", "-stream_loop", "-1", "-i", str(source), "-t", str(seconds), "-vf", vf,
            "-c:v", "libx264", "-preset", "veryfast", "-an", str(out)]


def caption_style(size: tuple[int, int]) -> str:
    """Caption style sized from the short side of the frame, so tall formats do not get oversized text.

    Captions are laid out on a 288-line grid that is stretched to the frame height, so sizes are given on that grid.
    """
    w, h = size
    grid = 288 / h
    short = min(w, h)
    return f"Fontsize={round(short * 0.07 * grid, 1)},Outline={max(1.5, round(short * 0.006 * grid, 1))},Shadow=1,MarginV=40"


DISSOLVE = 0.5
LOUDNESS = "loudnorm=I=-16:TP=-1.5:LRA=9,aresample=48000"
MIN_TITLE = 1.0  # a title on screen for less than this (seconds) cannot be read, so it is left out


def title_track(shots: list[Shot], size: tuple[int, int], dissolve: float) -> str:
    """Animated on-screen words, one title per shot: they slide up and grow in once the shot has taken over, then fade out.

    Written as an ASS subtitle file laid out on the frame's own pixel grid, so it fits every format.
    """
    w, h = size
    short = min(w, h)
    font, pad = round(short * 0.05), round(short * 0.013)
    left, base = round(w * 0.05), h - round(h * 0.08)
    drop = round(h * 0.035)

    def stamp(t: float) -> str:
        cs = round(t * 100)
        return f"{cs // 360000}:{cs // 6000 % 60:02d}:{cs // 100 % 60:02d}.{cs % 100:02d}"

    lines = [
        "[Script Info]", "ScriptType: v4.00+", f"PlayResX: {w}", f"PlayResY: {h}", "WrapStyle: 0", "ScaledBorderAndShadow: yes", "",
        "[V4+ Styles]",
        "Format: Name,Fontname,Fontsize,PrimaryColour,SecondaryColour,OutlineColour,BackColour,Bold,Italic,Underline,StrikeOut,"
        "ScaleX,ScaleY,Spacing,Angle,BorderStyle,Outline,Shadow,Alignment,MarginL,MarginR,MarginV,Encoding",
        f"Style: Title,Arial,{font},&H00FFFFFF,&H00FFFFFF,&H99140F0D,&H99140F0D,1,0,0,0,100,100,0,0,3,{pad},0,1,{left},{left},{base},1",
        "", "[Events]", "Format: Layer,Start,End,Style,Name,MarginL,MarginR,MarginV,Effect,Text",
    ]
    start = 0.0
    for shot in shots:
        end = start + shot.seconds
        words = re.sub(r"\{[^}]*\}", "", shot.caption or "")
        words = " ".join(re.sub(r"[{}\\]", "", words).split())
        on, off = start + dissolve + 0.1, end - dissolve
        if words and off - on >= MIN_TITLE:
            move = f"\\move({left},{base + drop},{left},{base},0,350)"
            grow = "\\fscx92\\fscy92\\t(0,350,\\fscx100\\fscy100)"
            lines.append(f"Dialogue: 0,{stamp(on)},{stamp(off)},Title,,0,0,0,,{{\\fad(300,350){move}{grow}}}{words}")
        start = end
    return "\n".join(lines) + "\n"


def dissolve_length(shots: list[Shot]) -> float:
    """How long neighbouring shots overlap: half a second, less when a shot is too short to give that much."""
    if len(shots) < 2:
        return 0.0
    return min(DISSOLVE, min(s.seconds for s in shots) / 2)


def join_command(clips: list[Path], seconds: list[int], dissolve: float, out: Path) -> list[str]:
    """Join the shots with dissolves; the film keeps the length of the shots added up, so the captions stay on time."""
    cmd = ["ffmpeg", "-y", "-loglevel", "error"]
    for clip in clips:
        cmd += ["-i", str(clip)]
    graph, label, start = [], "[0:v]", seconds[0]
    for index in range(1, len(clips)):
        last = index == len(clips) - 1
        graph.append(f"{label}[{index}:v]xfade=transition=fade:duration={dissolve}:offset={round(start - dissolve, 3)}"
                     f"[{'v' if last else f'x{index}'}]")
        label = f"[x{index}]"
        start += seconds[index]
    return cmd + ["-filter_complex", ";".join(graph), "-map", "[v]", "-c:v", "libx264", "-preset", "veryfast",
                  "-crf", "14", "-pix_fmt", "yuv420p", str(out)]


def final_command(joined: Path, voice: Path | None, music: Path | None, total: int, captions: bool, out: Path,
                  size: tuple[int, int] = (1920, 1080), titles: bool = False) -> list[str]:
    """Fade the picture and sound in and out; clean the voice, dip the music under it, level the mix.

    `captions` burns in captions.srt and `titles` the animated words in titles.ass, both read from the working folder.
    """
    cmd = ["ffmpeg", "-y", "-loglevel", "error", "-i", str(joined)]
    inputs = []
    if voice:
        cmd += ["-i", str(voice)]
        inputs.append("voice")
    if music:
        cmd += ["-stream_loop", "-1", "-i", str(music)]
        inputs.append("music")
    edge = round(min(0.5, total / 6), 3)
    fades = f"fade=t=in:st=0:d={edge},fade=t=out:st={round(total - edge, 3)}:d={edge}"
    picture = f"subtitles=captions.srt:force_style='{caption_style(size)}'," if captions else ""
    picture += "subtitles=titles.ass," if titles else ""
    picture += fades
    graph = []
    labels = []
    for index, name in enumerate(inputs, start=1):
        fit = f"apad=whole_dur={total},atrim=0:{total}"
        if name == "voice":
            graph.append(f"[{index}:a]highpass=f=80,acompressor=threshold=-18dB:ratio=3:attack=5:release=120,{fit}[voice]")
        else:
            graph.append(f"[{index}:a]volume={0.6 if voice else 1.0},{fit}[music]")
        labels.append(f"[{name}]")
    if len(labels) == 2:
        graph.append("[voice]asplit=2[voice_mix][voice_key]")
        graph.append("[music][voice_key]sidechaincompress=threshold=0.03:ratio=6:attack=25:release=450:makeup=1[ducked]")
        graph.append("[voice_mix][ducked]amix=inputs=2:duration=first:normalize=0[mixed]")
        labels = ["[mixed]"]
    if labels:
        graph.append(f"{labels[0]}{LOUDNESS},afade=t=out:st={round(total - edge, 3)}:d={edge}[a]")
    if graph or captions or titles:
        graph.insert(0, f"[0:v]{picture}[v]")
        cmd += ["-filter_complex", ";".join(graph), "-map", "[v]"]
    else:
        cmd += ["-vf", picture, "-map", "0:v"]
    if labels:
        cmd += ["-map", "[a]", "-c:a", "aac", "-b:a", "192k"]
    cmd += ["-c:v", "libx264", "-preset", "veryfast", "-crf", "20", "-pix_fmt", "yuv420p", "-t", str(total),
            "-movflags", "+faststart", str(out)]
    return cmd


def probe(path: Path) -> dict[str, Any]:
    run = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration:stream=codec_type,width,height",
                          "-of", "json", str(path)], capture_output=True, text=True, check=False)
    data = json.loads(run.stdout or "{}")
    video = next((s for s in data.get("streams", []) if s.get("codec_type") == "video"), {})
    return {"seconds": float(data.get("format", {}).get("duration", 0) or 0), "width": video.get("width"),
            "height": video.get("height"), "audio": any(s.get("codec_type") == "audio" for s in data.get("streams", []))}


def convert(args: list[str]) -> bool:
    """Run FFmpeg once on local files (a still resized, a sound re-encoded); True when it finished."""
    if shutil.which("ffmpeg") is None:
        return False
    return subprocess.run(["ffmpeg", "-y", "-loglevel", "error", *args], capture_output=True, check=False).returncode == 0


def frozen_stretches(path: Path) -> list[tuple[float, float]]:
    """Every stretch of a film where the picture does not change for a second or more, as (start, seconds)."""
    run = subprocess.run(["ffmpeg", "-hide_banner", "-nostats", "-i", str(path), "-map", "0:v:0", "-vf",
                          "freezedetect=n=-50dB:d=1", "-f", "null", "-"], capture_output=True, text=True, check=False)
    starts = [float(m) for m in re.findall(r"freeze_start: ([0-9.]+)", run.stderr)]
    lengths = [float(m) for m in re.findall(r"freeze_duration: ([0-9.]+)", run.stderr)]
    return list(zip(starts, lengths))


def picture_activity(path: Path) -> dict[str, float]:
    """How often something happens on screen: the longest quiet stretch (seconds, and where it starts) and the
    share of the film's seconds in which something happens. Looks ten times a second, at patches of the frame."""
    cols, rows = 40, 22
    run = subprocess.run(["ffmpeg", "-v", "error", "-i", str(path), "-map", "0:v:0", "-vf",
                          f"fps=10,scale=320:180,format=gray,tblend=all_mode=difference,scale={cols}:{rows}:flags=area",
                          "-f", "rawvideo", "-pix_fmt", "gray", "-"], capture_output=True, check=False)
    raw, step = run.stdout, cols * rows
    events = [max(raw[i:i + step]) > EVENT_LEVEL for i in range(0, len(raw) - step + 1, step)]
    if not events:  # FFmpeg could not read the picture, so nothing was seen to happen
        return {"longest_quiet": math.inf, "quiet_from": 0.0, "lively_share": 0.0}
    quiet = longest = longest_at = 0
    for index, event in enumerate(events):
        quiet = 0 if event else quiet + 1
        if quiet > longest:
            longest, longest_at = quiet, index + 1 - quiet
    # every one-second window, sliding a tenth at a time, so where the film's seconds happen to start never matters
    seconds = [any(events[i:i + 10]) for i in range(max(1, len(events) - 9))]
    return {"longest_quiet": longest / 10, "quiet_from": longest_at / 10, "lively_share": sum(seconds) / len(seconds)}


SHEET_ACROSS, SHEET_DOWN = 4, 3
SHEET_MAX_SIDE = 1024  # the largest picture the spend gate will count (spend.PICTURE_MAX_SIDE)


def _even(value: float) -> int:
    return max(2, int(value) // 2 * 2)


def contact_sheet(path: Path, out: Path, *, kind: str) -> Path | None:
    """One small JPEG the judge can look at: for a film, twelve moments spread across it in a 4 x 3 grid; for a
    picture, the picture itself made to fit. At most SHEET_MAX_SIDE a side. None when FFmpeg cannot read the file."""
    facts = probe(path) if shutil.which("ffprobe") else {}
    width, height = facts.get("width"), facts.get("height")
    if not width or not height:
        return None
    out.unlink(missing_ok=True)
    if kind == "video":
        seconds = facts.get("seconds") or 0
        if seconds <= 0:
            return None
        frames = SHEET_ACROSS * SHEET_DOWN
        tile_w = min(SHEET_MAX_SIDE / SHEET_ACROSS, SHEET_MAX_SIDE / SHEET_DOWN * width / height)
        tile_w, tile_h = _even(tile_w), _even(tile_w * height / width)
        args = ["-ss", f"{seconds / (2 * frames):.3f}", "-i", str(path), "-map", "0:v:0", "-vf",
                f"fps={frames}/{seconds:.3f},scale={tile_w}:{tile_h},setsar=1,tile={SHEET_ACROSS}x{SHEET_DOWN}",
                "-frames:v", "1", "-q:v", "4", str(out)]
    else:
        scale = min(1.0, SHEET_MAX_SIDE / max(width, height))
        args = ["-i", str(path), "-vf", f"scale={max(1, round(width * scale))}:{max(1, round(height * scale))},setsar=1",
                "-frames:v", "1", "-q:v", "3", str(out)]
    if not convert(args) or not out.is_file() or out.stat().st_size == 0:
        return None
    return out


def data_url(path: Path) -> str:
    """A JPEG or PNG as an inline picture a model can be sent."""
    kind = "png" if path.suffix.lower() == ".png" else "jpeg"
    return f"data:image/{kind};base64," + base64.b64encode(path.read_bytes()).decode("ascii")


def sound_facts(path: Path) -> dict[str, float] | None:
    """What the sound is like, measured: integrated loudness (LUFS), true peak (dBFS), length, and the share of it
    that is silent (below -45 dB for half a second or more). None when there is no sound FFmpeg can read."""
    if shutil.which("ffmpeg") is None or not probe(path).get("audio"):
        return None
    run = subprocess.run(["ffmpeg", "-hide_banner", "-nostats", "-i", str(path), "-map", "0:a:0", "-af",
                          "ebur128=peak=true,silencedetect=n=-45dB:d=0.5", "-f", "null", "-"],
                         capture_output=True, text=True, check=False)
    summary = run.stderr.rpartition("Summary:")[2]
    loud = re.search(r"I:\s+(-?[0-9.]+|-inf) LUFS", summary)
    peak = re.search(r"Peak:\s+(-?[0-9.]+|-inf) dBFS", summary)
    if run.returncode != 0 or loud is None or peak is None:
        return None
    seconds = probe(path)["seconds"] or 0.0
    starts = [float(m) for m in re.findall(r"silence_start: (-?[0-9.]+)", run.stderr)]
    lengths = [float(m) for m in re.findall(r"silence_duration: ([0-9.]+)", run.stderr)]
    silent = sum(lengths) + sum(max(0.0, seconds - start) for start in starts[len(lengths):])
    return {"loudness_lufs": float(loud.group(1)), "peak_dbfs": float(peak.group(1)), "seconds": round(seconds, 2),
            "silent_share": round(min(1.0, silent / seconds), 3) if seconds else 1.0}


def _render_checks(name: str, final: Path, total: float, size: tuple[int, int], sound: bool,
                   tolerance: float) -> list[dict[str, Any]]:
    """Measure one finished render: its length, frame size, sound, that the picture never stands still, and
    that something keeps happening on screen."""
    measured = probe(final)
    holds = frozen_stretches(final)
    longest = max(holds, key=lambda stretch: stretch[1], default=None)
    still = longest is not None and longest[1] >= MAX_HOLD
    activity = picture_activity(final)
    return [
        {"render": name, "check": "length", "ok": abs(measured["seconds"] - total) <= tolerance,
         "detail": f"{measured['seconds']:.1f}s of {total:g}s"},
        {"render": name, "check": "frame size", "ok": (measured["width"], measured["height"]) == size,
         "detail": f"{measured['width']}x{measured['height']}"},
        {"render": name, "check": "sound", "ok": measured["audio"] == sound,
         "detail": "voice/music present" if measured["audio"] else "silent"},
        {"render": name, "check": "picture keeps moving", "ok": not still,
         "detail": (f"holds still for {longest[1]:.1f}s from {longest[0]:.1f}s" if still else
                    f"never holds still for {MAX_HOLD:g}s or more")},
        {"render": name, "check": "something happens", "ok": activity["longest_quiet"] <= MAX_QUIET,
         "detail": (f"nothing new on screen for {activity['longest_quiet']:.1f}s from {activity['quiet_from']:.1f}s "
                    f"({MAX_QUIET:g}s at most)" if math.isfinite(activity["longest_quiet"])
                    else "the picture could not be read")},
        {"render": name, "check": "picture changes every second", "ok": activity["lively_share"] >= MIN_LIVELY,
         "detail": f"something happens in {activity['lively_share']:.0%} of its seconds ({MIN_LIVELY:.0%} at least)"},
    ]


def _run(cmd: list[str], cwd: Path, production: Production) -> None:
    production.commands.append(cmd)
    done = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, check=False)
    if done.returncode != 0:
        raise StudioError(f"ffmpeg failed: {(done.stderr or '').strip()[-400:]}")


def _spoken_guess(board: list[dict[str, Any]], rate: float = FAST_RATE) -> float:
    """How long the storyboard runs if every phrase is read at ``rate`` words a second."""
    beats = storyboard.parse([{**row, "base": {"kind": "living"}} for row in board], Path.cwd())
    for beat in beats:
        for phrase in beat.phrases:
            phrase.seconds = len(phrase.text.split()) / rate
    return storyboard.time_beats(beats)


QUIET_STEP = 0.3  # seconds apart that overlays timed to the sentences of a beat left without words appear


def _quiet_time(value: Any, field: str) -> Any:
    """A time set by a sentence that is no longer said, set by the picture instead: overlays keep their order a
    moment apart from the start, and anything held until a sentence ends is held until the beat ends."""
    m = storyboard._ANCHOR.fullmatch(value.strip()) if isinstance(value, str) else None
    if m is None or m.group(2) is None:
        return value
    if field == "until":
        return "end"
    t = QUIET_STEP * (int(m.group(2)) - 1 + (1 if m.group(3) else 0))
    if m.group(4):
        t += float(m.group(5)) * (1 if m.group(4) == "+" else -1)
    return round(max(t, 0.0), 2)


def _quiet_items(items: list[Any]) -> list[Any]:
    return [{k: _quiet_time(v, k) for k, v in item.items()} if isinstance(item, dict) else item for item in items]


def quiet_rows(board: list[dict[str, Any]], quiet: list[int]) -> list[dict[str, Any]]:
    """The storyboard with the beats at ``quiet`` (counted from 0) keeping their pictures and overlays but saying
    nothing, every time set by their sentences set by the picture instead."""
    out = []
    for i, row in enumerate(board):
        if i in quiet:
            row = {k: v for k, v in row.items() if k != "say"}
            for key in ("layers", "sounds"):
                if isinstance(row.get(key), list):
                    row[key] = _quiet_items(row[key])
        out.append(row)
    return out


def _quiet_to_fit(count: int, size: Callable[[int], float], fits: Callable[[list[int]], bool],
                  footage: Collection[int] = ()) -> list[int] | None:
    """The middle beats to leave without words, the longest spoken first, until the film fits: every shot stays,
    and the opening and close keep their words. Beats showing real ``footage`` lose their words last, because
    footage with nothing said over it proves nothing. None when even every middle beat without words does not fit."""
    quiet: list[int] = []
    talking = [i for i in range(1, count - 1) if size(i) > 0]
    while not fits(quiet):
        left = [i for i in talking if i not in quiet]
        if not left:
            return None
        quiet.append(max(left, key=lambda i: (i not in footage, size(i))))
    return quiet


def _cut_to_fit(count: int, size: Callable[[int], float], fits: Callable[[list[int]], bool]) -> list[int] | None:
    """The beats to keep when whole middle beats are cut, the longest first, until the rest fits: the opening and
    the close always stay. None when even those two alone do not fit."""
    keep = list(range(count))
    while not fits(keep):
        middle = keep[1:-1]
        if not middle:
            return None
        keep.remove(max(middle, key=size))
    return keep


def produce(
    brief: str,
    *,
    provider_id: str,
    model: str,
    visual_provider: str = "",
    visual_model: str = "",
    visual_kind: str = "image",
    voice_provider: str | None = None,
    voice_model: str | None = None,
    voice: str | None = None,
    music_provider: str | None = None,
    music_model: str | None = None,
    music_file: Path | None = None,
    seconds: int = 30,
    formats: tuple[str, ...] = ("16x9", "9x16", "1x1"),
    captions: bool = True,
    max_cost_usd: str | None = None,
    out_dir: Path,
    size_scale: float = 1.0,
    text_transport: live.Transport | None = None,
    media_transport: Any = None,
    media_get: Any = None,
    facts: dict[str, Any] | None = None,
    allow_commands: bool = False,
    script: dict[str, Any] | None = None,
) -> Production:
    """`script` is a writer's reply saved as script-written.json: the film is rebuilt from it without asking
    the writer again, and the engine still settles, fits and voices it as on a last try."""
    for tool in ("ffmpeg", "ffprobe"):
        if shutil.which(tool) is None:
            raise StudioError(f"{tool} is not installed; install FFmpeg (https://ffmpeg.org) and try again")
    if visual_kind not in ("image", "video"):
        raise StudioError("--visual-kind must be image or video")
    unknown = [f for f in formats if f not in FORMATS]
    if unknown:
        raise StudioError(f"unknown format {', '.join(unknown)}; use {', '.join(FORMATS)}")
    if not 3 <= seconds <= 600:
        raise StudioError("--seconds must be 3 to 600")
    paid = [p for p in (providers.find(provider_id),) if p is not None and not p.local]
    for service in (voice_provider, music_provider):
        found = media.find(service) if service else None
        if found is not None and not found.local:
            paid.append(found)
    if visual_provider:
        found = media.find(visual_provider)
        if found is not None and not found.local:
            paid.append(found)
    if paid and max_cost_usd is None:
        raise StudioError("name one spending limit for the whole video (--max-cost-usd)")
    budget = _Budget(max_cost_usd)
    out_dir = out_dir.resolve()  # FFmpeg runs inside this folder, so every path in it must be absolute
    out_dir.mkdir(parents=True, exist_ok=False)
    production = Production(out_dir)
    books = threading.Lock()  # lines of a local voice are spoken at the same time; the budget and the call log are not

    def record(role: str, result: Any, figure: Any) -> None:
        production.calls.append({"role": role, "status": result.status, "code": result.code, "usd": figure})
        if result.status == "refused" and result.code == "PHC-COST-0001":
            raise StudioError("spending limit reached")
        if result.status != "success":
            raise StudioError(f"{role}: {result.message}")

    try:
        lookup = _facts_lookup(facts) if facts else {}

        def make_media(kind: str, service: str, model_id: str, prompt: str, target: Path, params: dict[str, Any]) -> str:
            with books:
                limit = budget.next_limit()
            result = media.generate(kind, service, model_id, prompt=prompt, out=target, params=params,
                                    max_cost_usd=limit, transport=media_transport, get=media_get)
            figure = (result.cost or {}).get("usd")
            with books:
                if result.status != "refused":
                    budget.charge(figure)
                record(f"{kind}: {prompt[:40]}", result, figure)
            return str(result.path)

        def capture_still(ref: str | None, target: Path) -> str:
            item = lookup.get(ref or "")
            if item is None:
                raise StudioError(f"capture ref {ref!r} is not in the fact sheet")
            try:
                if item["kind"] == "command":
                    if not allow_commands:
                        raise StudioError(
                            "command capture shots need --allow-commands (running the commands in the fact sheet on this machine)"
                        )
                    cwd = Path(item["cwd"]) if item.get("cwd") else Path.cwd()
                    output = capture.run_command(item["argv"], cwd=cwd)
                    cmd_line = item.get("display") or " ".join(item["argv"])
                    return str(capture.render_card(cmd_line, output, target.with_suffix(".png"),
                                                   redact=capture.private_text()))
                return str(capture.render_page(item["url"], target.with_suffix(".png")))
            except capture.CaptureError as exc:
                raise StudioError(str(exc)) from exc

        recorded: dict[str, dict[str, Any]] = {}

        def footage(ref: str) -> dict[str, Any]:
            """The beat fields for one piece of real footage, recorded once and kept: a command is typed in a
            terminal and shows its real output, as it arrived, over the moving background; a page is used in the
            browser here and recorded, and plays in a window frame. Nothing is paid for."""
            if ref in recorded:
                return recorded[ref]
            item = lookup.get(ref)
            if item is None:
                raise StudioError(f"capture ref {ref!r} is not in the fact sheet")
            folder = out_dir / "footage" / (re.sub(r"[^A-Za-z0-9_-]+", "-", ref).strip("-")[:60] or "shot")
            try:
                if item["kind"] == "command":
                    if not allow_commands:
                        raise StudioError("command footage needs --allow-commands (running the commands in the fact "
                                          "sheet on this machine)")
                    cwd = Path(item["cwd"]) if item.get("cwd") else Path.cwd()
                    chunks = recording.record_command(item["argv"], cwd=cwd)
                    timeline = recording.terminal_timeline(item.get("display") or " ".join(item["argv"]), chunks,
                                                           **FOOTAGE_TERMINAL)
                    folder.mkdir(parents=True, exist_ok=True)
                    (folder / "terminal.json").write_text(json.dumps(timeline, indent=2) + "\n", encoding="utf-8")
                    found = {"base": {"kind": "living"}, "hold": timeline["seconds"],
                             "terminal": {"kind": "terminal", "timeline": timeline, "box": list(TERMINAL_BOX)}}
                else:
                    size = tuple(item.get("size") or FOOTAGE_PAGE_SIZE)
                    shot = recording.record_app(item["url"], item.get("steps") or FOOTAGE_PAGE_STEPS, folder,
                                                size=size, scale=max(1.0, 1920 / max(size)))
                    base = {"kind": "recording", "file": shot.video.relative_to(out_dir).as_posix(),
                            "frame": item.get("frame", "window"), "speed": FOOTAGE_SPEED}
                    found = {"base": base,
                             "hold": round(max(storyboard.MIN_BEAT, shot.seconds / FOOTAGE_SPEED), 3)}
            except capture.CaptureError as exc:
                raise StudioError(f"footage {ref!r}: {exc}") from exc
            recorded[ref] = found
            return found

        def with_footage(row: dict[str, Any]) -> dict[str, Any]:
            """The beat as it will be filmed: real footage recorded and put in, generated pictures still to come."""
            if row["base"]["kind"] != "capture":
                return {**row, "base": {"kind": "living"}}
            found = footage(row["base"]["ref"])
            out = {**row, "base": dict(found["base"]), "real": True,
                   "hold": max(float(row.get("hold") or 0), found["hold"])}
            if "terminal" in found:  # the writer's words go above and below the terminal, never over it
                slots = iter(TERMINAL_SLOTS)
                layers = [lay if "y" in lay or "box" in lay else {**lay, "y": next(slots, TERMINAL_SLOTS[-1])}
                          for lay in row.get("layers") or []]
                out["layers"] = [dict(found["terminal"]), *layers]
            return out

        def speak(text: str, name: str) -> Path:
            return Path(make_media("speech", voice_provider or "", voice_model or "", text, out_dir / "voice" / name,
                                   {"voice": voice} if voice else {}))

        # a voice on this machine costs nothing, so its lines are spoken at the same time; a paid one stays one at a
        # time, because each call is priced against what is left after the one before
        voice_profile = media.find(voice_provider) if voice_provider else None
        voice_workers = VOICE_WORKERS if voice_profile is not None and voice_profile.local else 1

        too_long = 0
        cut_said: list[str] = []  # the words of middle beats cut to fit, once the writer had no fixes left
        quiet_said: list[str] = []  # the words of middle beats that kept their shots but lost their words to fit
        limit = seconds + brief_slack(seconds)

        def quiet_board(board: list[dict[str, Any]], quiet: list[int]) -> None:
            quiet_said.extend(str(board[i].get("say") or "").strip() for i in sorted(quiet))
            board[:] = quiet_rows(board, quiet)

        def cut_board(board: list[dict[str, Any]], keep: list[int]) -> None:
            cut_said.extend(str(row.get("say") or "").strip() for i, row in enumerate(board) if i not in keep)
            board[:] = [board[i] for i in keep]

        def voice_board(board: list[dict[str, Any]], last: bool) -> tuple[list[storyboard.Beat], float, str | None]:
            """Speak the storyboard's words and time it. A film the chosen voice makes too long is a problem to send
            back, with that voice's own pace, and its spoken files are set aside so the next script starts fresh.
            On the ``last`` chance, whole middle beats are cut to fit first."""
            nonlocal too_long
            try:
                beats = storyboard.parse([with_footage(row) for row in board], out_dir)
                asked = [b.cut for b in beats]  # timing settles the joins left on auto; a shorter film settles its own
                if any(b.phrases for b in beats):
                    storyboard.voice(beats, speak, workers=voice_workers)
            except storyboard.StoryboardError as exc:
                raise StudioError(str(exc)) from exc

            def trial(kept: list[int]) -> list[storyboard.Beat]:
                run = [copy.copy(beats[i]) for i in kept]
                for n, (i, beat) in enumerate(zip(kept, run), start=1):
                    beat.number, beat.cut = n, asked[i]
                return run

            def hushed(quiet: list[int]) -> list[storyboard.Beat]:
                run = trial(list(range(len(beats))))
                for i in quiet:
                    run[i].phrases = []
                    run[i].layers, run[i].sounds = _quiet_items(run[i].layers), _quiet_items(run[i].sounds)
                return run

            total = storyboard.time_beats(beats)
            if total > limit and last:  # words go before shots: a beat without words still shows its picture
                spoken = lambda i: sum(p.seconds for p in beats[i].phrases)  # noqa: E731
                quiet = _quiet_to_fit(len(beats), spoken, lambda q: storyboard.time_beats(hushed(q)) <= limit,
                                       [i for i, beat in enumerate(beats) if beat.real])
                if quiet is not None:
                    beats = hushed(quiet)
                    quiet_board(board, quiet)
                    total = storyboard.time_beats(beats)
                else:
                    keep = _cut_to_fit(len(beats), spoken, lambda kept: storyboard.time_beats(trial(kept)) <= limit)
                    if keep is not None:
                        beats = trial(keep)
                        cut_board(board, keep)
                        total = storyboard.time_beats(beats)
            if total <= limit:
                length = storyboard.fill_to(beats, seconds)
                try:
                    storyboard.check_mix(beats, length)
                except storyboard.StoryboardError as exc:
                    if not last:
                        return beats, length, f"{exc}: use fewer footage refs, or put them on shorter beats"
                    length = trim_real(beats, board, seconds)
                return beats, length, None
            too_long += 1
            if (out_dir / "voice").is_dir():
                (out_dir / "voice").rename(out_dir / f"voice-too-long-{too_long}")
            words = sum(len(p.text.split()) for b in beats for p in b.phrases)
            talk = sum(p.seconds for b in beats for p in b.phrases)
            if not words:
                fit = script_budget(seconds)
                return beats, total, (f"the script is too long: its beats run {total:.1f} seconds, and the film must be "
                                      f"about {seconds} seconds. Use {fit['fewest']} to {fit['most']} beats")
            rate = words / talk
            return beats, total, (f"the script is too long: spoken by the chosen voice it runs {total:.1f} seconds, and "
                                  f"the film must be about {seconds} seconds. This voice speaks about {rate:.1f} words a "
                                  f"second, so use {script_budget(seconds, rate)['words']} words in all at most")

        def trim_real(beats: list[storyboard.Beat], board: list[dict[str, Any]], seconds: float) -> float:
            """With no fixes left, the longest real beats stand on a moving background until footage fills a third
            of the film or less, each one noted."""
            length = storyboard.fill_to(beats, seconds)
            while True:
                try:
                    storyboard.check_mix(beats, length)
                    return length
                except storyboard.StoryboardError:
                    beat = max((b for b in beats if b.real), key=lambda b: b.span)
                    row = board[beat.number - 1]
                    # footage only exists for a product with a fact sheet, and a picture model would draw whatever the
                    # line names (labs, workers, machines) and none of it is the product: a moving background it is
                    instead = "stands on a moving background instead"
                    production.checks.append({
                        "render": "all", "check": "real footage cut to a third", "ok": True,
                        "detail": f"after {SCRIPT_FIXES} fixes real footage still filled more than a third of the "
                                  f"film, so beat {beat.number} ({row['base'].get('ref')}) {instead}"})
                    row["base"] = {"kind": "living"}
                    beat.base, beat.real, beat.hold, beat.meta = {"kind": "living"}, False, row.get("hold"), None
                    beat.layers = [lay for lay in beat.layers if lay.get("kind") != "terminal"]
                    length = storyboard.fill_to(beats, seconds)

        def grow_narration(board: list[dict[str, Any]]) -> tuple[int, int] | None:
            """With no fixes left and narration too thin to fill the film, the writer adds a sentence or two to one
            beat at a time, from the brief and the facts only, until the film says enough. An addition that states a
            figure the facts never give is not used. Returns the words before and after, or None if nothing ran."""
            aim = narration_aim(seconds)
            before = _words(board)
            if not voice_provider or not before or before >= aim:
                return None
            lines_known = [str(facts.get(k, "")).strip() for k in ("product", "summary")] if facts else []
            lines_known += [str(f) for f in (facts or {}).get("facts") or []]
            known = "\n".join(f"- {line}" for line in lines_known if line) or "- (none listed)"
            for index, row in enumerate(board):
                if _words(board) >= aim:
                    break
                if not isinstance(row.get("say"), str) or not row["say"].strip():
                    continue  # a beat written to be silent stays silent
                need = max(8, math.ceil((aim - _words(board)) / (len(board) - index)))
                lines = "\n".join(f"{n}. {_spoken(r)}" for n, r in enumerate(board, start=1))
                reply = live.run_prompt(provider_id, model, prompt=_GROW.format(
                    seconds=seconds, lines=lines, words=need, number=index + 1, brief=brief, facts=known),
                    max_output_tokens=400, max_cost_usd=budget.next_limit(), transport=text_transport,
                    json_reply=True)
                figure = (reply.cost or {}).get("usd")
                budget.charge(figure if reply.status != "refused" else 0)
                production.calls.append({"role": "narration", "status": reply.status, "code": reply.code,
                                         "usd": figure})
                if reply.status != "success":
                    break  # the film goes on with what it has; nothing more is asked
                try:
                    add = " ".join(str(_json_object(reply.output_text).get("add", "")).split())
                except StudioError:
                    continue
                if not add or len(add.split()) > 3 * need:
                    continue
                if add[-1] not in ".!?…":
                    add += "."
                if facts and _invented([{"say": add, "base": {"kind": "living"}}], brief, facts):
                    continue
                row["say"] = f"{row['say'].strip()} {add}"
            return before, _words(board)

        task = script_prompt(brief, seconds, facts)
        prompt, role = task, "script"
        written: dict[str, Any] | None = None  # the writer's reply the film is built from, saved to rebuild it
        for attempt in range(SCRIPT_FIXES, 1 + SCRIPT_FIXES) if script is not None else range(1 + SCRIPT_FIXES):
            if script is not None:  # a saved script stands in for the writer, with no fixes left to ask for
                reply, reply_text = None, json.dumps(script, ensure_ascii=False)
            else:
                reply = live.run_prompt(provider_id, model, prompt=prompt, max_output_tokens=SCRIPT_ROOM,
                                        max_cost_usd=budget.next_limit(), transport=text_transport, json_reply=True)
                figure = (reply.cost or {}).get("usd")
                budget.charge(figure if reply.status != "refused" else 0)
                record(role, reply, figure)
                reply_text = reply.output_text or ""
            board: list[dict[str, Any]] | None = None
            plan: tuple[str, str, str, list[Shot]] | None = None
            problem: str | None = None
            data: dict[str, Any] | None = None
            try:
                data = _json_object(reply_text)
                written = copy.deepcopy(data)
                if "beats" in data or "shots" not in data:
                    board = beats_from(data, facts)
                    guess = _spoken_guess(board)
                    if guess > limit and attempt == SCRIPT_FIXES:  # no fixes left: quiet middle beats, then cut them
                        rows = board
                        talk = lambda i: _spoken_guess([rows[i]]) if rows[i].get("say") else 0.0  # noqa: E731
                        quiet = _quiet_to_fit(len(rows), talk, lambda q: _spoken_guess(quiet_rows(rows, q)) <= limit,
                                              [i for i, row in enumerate(rows) if row["base"]["kind"] == "capture"])
                        if quiet is not None:
                            quiet_board(board, quiet)
                        else:
                            keep = _cut_to_fit(len(rows), talk, lambda kept: _spoken_guess([rows[i] for i in kept]) <= limit)
                            if keep is not None:
                                cut_board(board, keep)
                        guess = _spoken_guess(board)
                    if guess > limit:
                        fit = script_budget(seconds)
                        problem = (f"the script is too long: even read quickly it runs about {guess:.0f} seconds, and "
                                   f"the film must be about {seconds} seconds. Use {fit['fewest']} to {fit['most']} beats "
                                   f"and {fit['words']} words in all at most")
                else:
                    plan = plan_from(data, seconds, facts)
            except StudioError as exc:
                problem = str(exc)
                if data is not None and board is None and plan is None:
                    problem = "; ".join(script_problems(data, facts)) or problem  # all of them, not just the first
            if problem is not None and attempt == SCRIPT_FIXES and board is None and plan is None and data:
                cleaned, dropped = untime_unreadable(data, facts)  # the last chance is gone: keep what can be read
                if dropped:
                    written = copy.deepcopy(cleaned)
                    try:
                        board = beats_from(cleaned, facts)
                    except StudioError:
                        pass
                    else:
                        data, problem = cleaned, None
                        production.checks.append({
                            "render": "all", "check": "unreadable parts dropped",
                            "ok": not any("left out" in d for d in dropped),
                            "detail": f"after {SCRIPT_FIXES} fixes these parts still could not be read, so stray text "
                                      f"and overlays or sounds the engine cannot draw are left out, and times and "
                                      f"paces play at their default: "
                                      f"{'; '.join(dropped)}"})
            if problem is None and board is not None:
                ask = {"brief": brief, "seconds": seconds, "facts": facts,
                       "footage": usable_footage(facts, allow_commands), "voiced": bool(voice_provider),
                       "pictures": bool(visual_provider and visual_model)}
                if attempt < SCRIPT_FIXES:
                    problem = "; ".join(script_gaps(board, **ask)) or None
                else:  # no fixes left: the engine settles what is missing itself and says what it did
                    production.checks = [c for c in production.checks
                                         if c["check"] not in ("script settled", "narration grown")]
                    grown = grow_narration(board)
                    if grown:
                        production.checks.append({
                            "render": "all", "check": "narration grown", "ok": True,
                            "detail": f"after {SCRIPT_FIXES} fixes the narration was still {grown[0]} words over "
                                      f"{seconds} seconds, so the engine had the writer add to it beat by beat from "
                                      f"the brief and facts: it now says {grown[1]} words"})
                    notes = settle_gaps(board, **ask)
                    if notes:
                        production.checks.append({
                            "render": "all", "check": "script settled", "ok": True,
                            "detail": f"after {SCRIPT_FIXES} fixes the script still lacked these, so the engine "
                                      f"settled them: {'; '.join(notes)}"})
            if problem is None and board is not None:
                unmade = [n for n, row in enumerate(board, start=1) if row["base"]["kind"] == "generate"]
                if unmade and (not visual_provider or not visual_model):  # no picture service: the motion layers carry it
                    for number in unmade:
                        board[number - 1]["base"] = {"kind": "living"}
                    production.checks = [c for c in production.checks if c["check"] != "no picture service"]
                    production.checks.append({
                        "render": "all", "check": "no picture service", "ok": True,
                        "detail": f"no --visual-provider was given, so beats {', '.join(map(str, unmade))} stand on a "
                                  f"moving background instead of a generated picture (see `proofhouse media list`)"})
                for number, row in enumerate(board, start=1):
                    for lay in row.get("layers") or []:
                        if (isinstance(lay, dict) and lay.get("kind") in ("image", "video") and "file" not in lay
                                and isinstance(lay.get("prompt"), str) and lay["prompt"].strip()
                                and (not visual_provider or not visual_model)):
                            raise StudioError(
                                f"beat {number}: {lay['kind']} layers need --visual-provider and --visual-model "
                                f"(see `proofhouse media list`)")
                if any(row.get("say") for row in board) and not voice_provider:
                    raise StudioError("a film with words needs a voice service to speak them (--voice-provider)")
                timed, length, problem = voice_board(board, attempt == SCRIPT_FIXES)
            if problem is None:
                break
            cut = reply is not None and reply.cut_off
            if cut:
                problem += "; your reply was cut off before it ended, so keep it shorter"
            if attempt == SCRIPT_FIXES:  # keep what it said last, so the failure can be read
                (out_dir / "script-reply.txt").write_text(reply_text, encoding="utf-8")
                after = ("the reply was cut off because the model ran out of room. A model on this machine may have a "
                         "small window: start llama-server with -c 16384 (for Ollama, OLLAMA_CONTEXT_LENGTH=16384), or try another model"
                         if cut else "try another model")
                if script is not None:
                    raise StudioError(f"the saved script cannot be made into a film: {problem}")
                raise StudioError(f"{problem} (the script writer's last reply is in script-reply.txt); {after}")
            # what it wrote goes back without its indents, so the fix fits in a small model's window
            said = reply_text if data is None else json.dumps(data, ensure_ascii=False, separators=(",", ":"))
            prompt, role = _FIX.format(problem=problem, task=task, reply=said[:6000]), "script fix"
        if written is not None:
            (out_dir / "script-written.json").write_text(json.dumps(written, indent=2, ensure_ascii=False) + "\n",
                                                         encoding="utf-8")

        if board is not None:
            if quiet_said:
                quoted = ", ".join(f"'{s}'" for s in quiet_said)
                production.checks.append({
                    "render": "all", "check": "middle beats kept without words to fit", "ok": True,
                    "detail": f"after {SCRIPT_FIXES} fixes the script still ran over {seconds} seconds, so these middle "
                              f"beats keep their pictures but no longer say: {quoted}"})
            if cut_said:
                quoted = ", ".join(f"'{s}'" for s in cut_said)
                production.checks.append({
                    "render": "all", "check": "middle beats cut to fit", "ok": True,
                    "detail": f"after {SCRIPT_FIXES} fixes the script still ran over {seconds} seconds, so these middle "
                              f"beats were cut and the opening and close kept: {quoted}"})
            production.title, production.music_brief = str(data.get("title", "")).strip(), str(data.get("music", "")).strip()
            # a model's beats are sparse, so the engine's own words fill their quiet stretches (storyboard.EXTRAS)
            look = str(data.get("look", "")).strip() or DEFAULT_LOOK  # every picture shares it, so they read as one film
            asked = _asks_text(look)
            if asked:  # the look goes into every picture, so lettering it asks for would be in all of them
                look = _without_text(look) or DEFAULT_LOOK
                production.checks.append({
                    "render": "all", "check": "look without text", "ok": True,
                    "detail": f"the film's look asked for {', '.join(asked)}, which a picture model draws as made-up "
                              f"text in every picture, so it is now: {look}"})
            script = {"title": production.title, "music": production.music_brief, "look": look, "extras": "fill",
                      "beats": board}
            for row, beat in zip(board, timed):  # keep the spoken files, so nothing is spoken twice
                if beat.phrases and row.pop("say", None) is not None:
                    row["phrases"] = [{"text": p.text, "file": Path(p.file).relative_to(out_dir).as_posix()}
                                      for p in beat.phrases]
            (out_dir / "script.json").write_text(json.dumps(script, indent=2) + "\n", encoding="utf-8")
            (out_dir / "shots").mkdir()
            for number, (row, beat) in enumerate(zip(board, timed), start=1):
                base, target = row["base"], out_dir / "shots" / f"beat-{number:02d}"
                if base["kind"] == "capture":
                    board[number - 1] = with_footage(row)
                elif base["kind"] == "generate":
                    params = ({"seconds": max(2, min(10, math.ceil(beat.frames / beat.fps)))} if visual_kind == "video"
                              else {"size": "1792x1024"})
                    file = make_media(visual_kind, visual_provider, visual_model, picture_prompt(base["prompt"], look),
                                      target, params)
                    row["base"] = {"kind": visual_kind, "file": Path(file).relative_to(out_dir).as_posix()}
                for index, lay in enumerate(row.get("layers") or [], start=1):
                    if (isinstance(lay, dict) and lay.get("kind") in ("image", "video") and "file" not in lay
                            and isinstance(lay.get("prompt"), str) and lay["prompt"].strip()):
                        lkind = lay["kind"]
                        lparams = ({"seconds": max(2, min(10, math.ceil(beat.frames / beat.fps)))} if lkind == "video"
                                   else {"size": "1792x1024"})
                        lfile = make_media(lkind, visual_provider, visual_model, picture_prompt(lay["prompt"], look),
                                           out_dir / "shots" / f"beat-{number:02d}-layer-{index:02d}", lparams)
                        row["layers"][index - 1] = {**{k: v for k, v in lay.items() if k != "prompt"},
                                                    "file": Path(lfile).relative_to(out_dir).as_posix()}
            if music_file is not None:
                production.music_file = str(shutil.copy2(music_file, out_dir / f"music{music_file.suffix}"))
            elif music_provider and production.music_brief:
                production.music_file = make_media("music", music_provider, music_model or "", production.music_brief,
                                                   out_dir / "music", {"seconds": math.ceil(max(length, seconds))})

            production = assemble_beats(out_dir, script, formats=formats, size_scale=size_scale, captions=captions,
                                        speak=speak, music_file=production.music_file, production=production,
                                        seconds=seconds)
            (out_dir / "script.json").write_text(json.dumps(script, indent=2) + "\n", encoding="utf-8")
            production.spent_usd = budget.spent
            _write_record(production, brief)
            return production

        assert plan is not None
        title, narration, music_brief, shots = plan
        production.title, production.voiceover, production.music_brief, production.shots = title, narration, music_brief, shots
        (out_dir / "script.json").write_text(json.dumps({"title": title, "voiceover": narration, "music": music_brief,
                                                          "shots": [vars(s) for s in shots]}, indent=2) + "\n", encoding="utf-8")

        needs_generated = any(s.source == "generate" for s in shots)
        if needs_generated and (not visual_provider or not visual_model):
            raise StudioError("generated shots need --visual-provider and --visual-model (see `proofhouse media list`)")
        has_capture = any(s.source == "capture" for s in shots)
        assemble_kind = "mixed" if has_capture else visual_kind

        (out_dir / "shots").mkdir()
        for index, shot in enumerate(shots, start=1):
            target = out_dir / "shots" / f"shot-{index:02d}"
            if shot.source == "capture":
                shot.file = capture_still(shot.ref, target)
            else:
                params = {"seconds": shot.seconds} if visual_kind == "video" else {"size": "1792x1024"}
                shot.file = make_media(visual_kind, visual_provider, visual_model, shot.visual, target, params)
        if voice_provider and narration:
            production.voice_file = make_media("speech", voice_provider, voice_model or "", narration, out_dir / "voice",
                                               {"voice": voice} if voice else {})
        if music_file is not None:
            production.music_file = str(shutil.copy2(music_file, out_dir / f"music{music_file.suffix}"))
        elif music_provider and music_brief:
            production.music_file = make_media("music", music_provider, music_model or "", music_brief, out_dir / "music",
                                               {"seconds": sum(s.seconds for s in shots)})
    except StudioError as exc:
        production.stopped = str(exc)
        production.spent_usd = budget.spent
        _write_record(production, brief)
        return production

    production = assemble(
        out_dir, shots, visual_kind=assemble_kind, formats=formats, size_scale=size_scale, captions=captions,
        voice_file=production.voice_file, music_file=production.music_file, production=production,
    )
    production.spent_usd = budget.spent
    _write_record(production, brief)
    return production


_STILL_SUFFIXES = frozenset({".png", ".jpg", ".jpeg", ".webp", ".gif", ".bmp"})


VOICE_MARGIN = 0.5  # seconds of picture left after the last word
VOICE_FITS = 0.25  # a voice this much past the film's end still fits


def _fit_to_voice(shots: list[Shot], spoken: float) -> tuple[float, int]:
    """When the voice runs past the film, lengthen the shots a whole second at a time until it ends with a little
    picture left. Each second goes to the shot whose words are most crowded for its length. A voice that already
    fits is left alone. Returns the voice's length and the film's length before."""
    before = sum(s.seconds for s in shots)
    if spoken <= before + VOICE_FITS:
        return spoken, before
    while shots and sum(s.seconds for s in shots) < spoken + VOICE_MARGIN:
        crowded = max(shots, key=lambda s: (len(s.caption.split()) or 0.1) / max(s.seconds, 1))
        crowded.seconds += 1
    return spoken, before


def assemble(
    out_dir: Path,
    shots: list[Shot],
    *,
    visual_kind: str,
    formats: tuple[str, ...],
    size_scale: float = 1.0,
    captions: bool = True,
    voice_file: str | None = None,
    music_file: str | None = None,
    production: Production | None = None,
    titles: bool | None = None,
) -> Production:
    """Cut shots to length, join, mix audio, burn captions or animated titles, and measure each render.

    `titles` puts each shot's words on screen as animated titles. Left as None, they appear whenever captions are not burned in.
    """
    if production is None:
        production = Production(out_dir)
    else:
        production.folder = out_dir
    production.voice_file = voice_file
    production.music_file = music_file
    fitted = _fit_to_voice(shots, probe(Path(voice_file))["seconds"]) if voice_file else None
    total = sum(s.seconds for s in shots)
    (out_dir / "captions.srt").write_text(srt(shots), encoding="utf-8")
    has_captions = captions and any(s.caption for s in shots)
    has_titles = (not has_captions if titles is None else titles) and any(s.caption for s in shots)
    work = out_dir / "work"
    work.mkdir()
    try:
        if fitted is not None:
            spoken, before = fitted
            production.checks.append({
                "render": "all", "check": "voice fits the film", "ok": spoken <= total + VOICE_FITS,
                "detail": f"{spoken:.1f}s of voice in a {total}s film" + (
                    f"; the shots were lengthened from {before}s to {total}s to fit it" if total > before else "")})
        for name in formats:
            w, h = FORMATS[name]
            size = (int(w * size_scale) // 2 * 2, int(h * size_scale) // 2 * 2)
            clips = []
            dissolve = dissolve_length(shots)
            for index, shot in enumerate(shots, start=1):
                if not shot.file:
                    raise StudioError(f"shot {index} has no file")
                clip = work / f"{name}-shot-{index:02d}.mp4"
                kind = visual_kind
                if visual_kind == "mixed":
                    is_still = Path(shot.file).suffix.lower() in _STILL_SUFFIXES
                    kind = ("still" if shot.source == "capture" else "image") if is_still else "video"
                # every shot after the first starts one dissolve early, under the end of the shot before it
                _run(shot_command(Path(shot.file), kind, shot.seconds + (dissolve if index > 1 else 0), size, clip, index - 1),
                     out_dir, production)
                clips.append(clip)
            joined = work / f"{name}-joined.mp4"
            if len(clips) == 1:
                joined = clips[0]
            else:
                _run(join_command(clips, [s.seconds for s in shots], dissolve, joined), work, production)
            final = out_dir / f"video-{name}.mp4"
            if has_titles:
                (out_dir / "titles.ass").write_text(title_track(shots, size, dissolve), encoding="utf-8")
            _run(final_command(joined, Path(production.voice_file) if production.voice_file else None,
                               Path(production.music_file) if production.music_file else None, total, has_captions, final, size,
                               has_titles),
                 out_dir, production)
            production.renders[name] = str(final)
            production.checks += _render_checks(name, final, total, size, bool(production.voice_file or production.music_file),
                                                max(1.0, total * 0.05))
        production.checks.append({"render": "all", "check": "captions match the script",
                                  "ok": srt(shots) == (out_dir / "captions.srt").read_text(encoding="utf-8"),
                                  "detail": f"{sum(1 for s in shots if s.caption)} captions"})
    except StudioError as exc:
        production.stopped = str(exc)
    shutil.rmtree(work, ignore_errors=True)
    _set_aside_failed(production)
    return production


def _unvoiced(text: str, name: str) -> Path:
    raise StudioError(f"phrase {name} ({text[:40]!r}) has no voice file; give it one, or name a voice service to speak it")


def _beat_record(beat: storyboard.Beat, root: Path) -> dict[str, Any]:
    def name(path: Any) -> str | None:
        if not path:
            return None
        path = Path(path)
        return path.relative_to(root).as_posix() if path.is_relative_to(root) else path.name

    return {"beat": beat.number, "start": round(beat.start, 3), "seconds": round(beat.span, 3), "cut": beat.cut,
            "energy": beat.energy, "real": beat.real, "base": beat.base["kind"], "file": name(beat.base.get("file")),
            "phrases": [{"text": p.text, "start": round(p.start, 3), "seconds": round(p.seconds, 3), "file": name(p.file)}
                        for p in beat.phrases]}


def assemble_beats(
    out_dir: Path,
    board: Any,
    *,
    formats: tuple[str, ...],
    size_scale: float = 1.0,
    captions: bool = True,
    speak: Callable[[str, str], Path] | None = None,
    music_file: str | None = None,
    production: Production | None = None,
    seconds: float | None = None,
) -> Production:
    """Make a film from a storyboard of beats, every file in it named inside ``out_dir``.

    Each phrase is spoken (``speak(text, name)``, for phrases with no file) and measured, and the beats are timed to
    the words. Then, for each format, every beat's motion scene is rendered, the beats are joined with their
    transitions, the sound design is laid on its own track, music and sounds dip under every line, captions are
    burned in, and the render is measured. Given ``seconds``, a film shorter than that is held out to it, and
    its length is checked against it.
    """
    if production is None:
        production = Production(out_dir)
    else:
        production.folder = out_dir
    production.music_file = music_file
    work = out_dir / "work"
    work.mkdir()
    try:
        beats = storyboard.parse(board, out_dir)
        storyboard.voice(beats, speak or _unvoiced)
        total = storyboard.fill_to(beats, seconds) if seconds else storyboard.time_beats(beats)
        share = storyboard.check_mix(beats, total)
        production.beats = [_beat_record(b, out_dir) for b in beats]
        production.voiceover = " ".join(p.text for b in beats for p in b.phrases)
        spans = storyboard.speech_spans(beats)
        text = storyboard.captions(beats)
        (out_dir / "captions.srt").write_text(text, encoding="utf-8")
        voice_cmd = storyboard.voice_command(beats, total, out_dir / "voice.wav")
        if voice_cmd:
            _run(voice_cmd, out_dir, production)
            production.voice_file = str(out_dir / "voice.wav")
        for name in formats:
            w, h = FORMATS[name]
            size = (int(w * size_scale) // 2 * 2, int(h * size_scale) // 2 * 2)
            planned = storyboard.scenes(beats, size)
            clips = motion.render_all([(sc, work / f"{name}-beat-{beat.number:02d}.mp4")
                                       for beat, sc in zip(beats, planned)], workers=RENDER_WORKERS)
            joined = clips[0]
            if len(clips) > 1:
                joined = work / f"{name}-joined.mp4"
                _run(storyboard.join_command(clips, beats, joined), work, production)
            effects = sound.mix(storyboard.sound_events(beats, planned), total, work / f"{name}-sounds.wav")
            final = out_dir / f"video-{name}.mp4"
            burn = f"subtitles=captions.srt:force_style='{caption_style(size)}'" if captions and text else ""
            _run(storyboard.mix_command(joined, Path(production.voice_file) if production.voice_file else None,
                                        Path(music_file) if music_file else None, effects, total, spans, final,
                                        loudness=LOUDNESS, picture_filter=burn), out_dir, production)
            _fit_delivery(final, total, work, production)
            production.renders[name] = str(final)
            production.checks += _render_checks(name, final, total, size, True, 0.1)
            production.checks.append(_size_check(name, final))
        last = max((p.start + p.seconds for b in beats for p in b.phrases), default=0.0)
        production.checks += [
            {"render": "all", "check": "voice fits the film", "ok": last <= total + 0.01,
             "detail": f"the last word ends at {last:.2f}s of a {total:.2f}s film" if last else "no words spoken"},
            {"render": "all", "check": "real footage share", "ok": share <= storyboard.REAL_SHARE + 1e-9,
             "detail": f"{share:.0%} of the film is real product footage (a third at most)"},
            {"render": "all", "check": "captions match the script",
             "ok": text == (out_dir / "captions.srt").read_text(encoding="utf-8"),
             "detail": f"{sum(len(b.phrases) for b in beats)} captions"},
        ]
        if seconds:
            production.checks.append({"render": "all", "check": "length matches the brief",
                                      "ok": abs(total - seconds) <= brief_slack(seconds),
                                      "detail": f"{total:.1f}s of the {seconds:g}s asked"})
    except (StudioError, storyboard.StoryboardError, motion.MotionError, sound.SoundError) as exc:
        production.stopped = str(exc)
    shutil.rmtree(work, ignore_errors=True)
    _set_aside_failed(production)
    return production


def _fit_delivery(final: Path, total: float, work: Path, production: Production, cap: int = storyboard.DELIVERY_CAP) -> None:
    """A finished film over the size cap is squeezed in two passes, so it can be uploaded. One under it is left alone."""
    if final.stat().st_size <= cap:
        return
    small = final.with_name(final.stem + ".small.mp4")
    one, two = storyboard.squeeze_commands(final, total, cap, small, work / f"{final.stem}-pass")
    _run(one, work, production)
    _run(two, work, production)
    small.replace(final)


def _size_check(name: str, final: Path, cap: int = storyboard.DELIVERY_CAP) -> dict[str, Any]:
    size = final.stat().st_size
    return {"render": name, "check": "small enough to upload", "ok": size <= cap,
            "detail": f"{size / 2**20:.1f} MiB of {cap / 2**20:.0f} MiB"}


def _set_aside_failed(production: Production) -> None:
    """A render with a failed check is renamed ``video-<shape>.failed.mp4``, so it never sits there looking finished.
    It is kept, and still listed, so it can be looked at and judged."""
    for name, path in list(production.renders.items()):
        failed = [c for c in production.checks if c["render"] in (name, "all") and not c["ok"]]
        final = Path(path)
        if failed and final.is_file() and not final.name.endswith(".failed.mp4"):
            aside = final.with_name(final.stem + ".failed.mp4")
            aside.unlink(missing_ok=True)
            final.replace(aside)
            production.renders[name] = str(aside)


def _write_record(production: Production, brief: str) -> None:
    record = {
        "schema": "proofhouse.studio/v1",
        "proofhouse_version": __version__,
        "brief": brief,
        "title": production.title,
        "stopped": production.stopped,
        "spent_usd_estimated": format(production.spent_usd, "f"),
        "shots": [vars(s) for s in production.shots],
        "beats": production.beats,
        "voice_file": production.voice_file,
        "music_file": production.music_file,
        "renders": production.renders,
        "checks": production.checks,
        "calls": production.calls,
        "ffmpeg": [" ".join(c) for c in production.commands],
    }
    (production.folder / "studio.json").write_text(json.dumps(record, indent=2, default=str) + "\n", encoding="utf-8")
