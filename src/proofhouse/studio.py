class _Budget:
    def __init__(self, limit: str | None) -> None:
        try:
            self.left = Decimal(limit) if limit is not None else None
        except InvalidOperation:
            raise StudioError("--max-cost-usd must be a decimal such as 5.00") from None
        self.spent = Decimal(0)

    def next_limit(self) -> str | None:
        if self.left is None:
            return None
        # nothing left still asks the spend gate: a call on this machine is free and goes through, a paid one is
        # refused there, and that refusal stops the film with "spending limit reached"
        return format(max(self.left, Decimal(0)), "f")

    def charge(self, figure: Any) -> None:
        try:
            amount = Decimal(str(figure))
        except (InvalidOperation, ValueError):
            return
        if amount.is_finite() and amount >= 0:
            self.spent += amount
            if self.left is not None:
                self.left -= amount


def _json_object(text: str | None) -> dict[str, Any]:
    match = re.search(r"\{.*\}", text or "", flags=re.S)
    try:
        data = json.loads(match.group(0)) if match else None
    except ValueError:
        data = None
    if not isinstance(data, dict):
        raise StudioError("the reply was not JSON in the planned shape")
    return data


def load_facts(path: Path) -> dict[str, Any]:
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, ValueError):
        raise StudioError(f"fact sheet {path} is not valid JSON") from None
    if not isinstance(raw, dict):
        raise StudioError("fact sheet must be a JSON object")
    product = raw.get("product")
    if not isinstance(product, str) or not product.strip():
        raise StudioError("fact sheet needs a non-empty product")
    summary = raw.get("summary")
    if not isinstance(summary, str) or not summary.strip():
        raise StudioError("fact sheet needs a non-empty summary")
    facts_list = raw.get("facts", [])
    if facts_list is None:
        facts_list = []
    if not isinstance(facts_list, list) or any(not isinstance(item, str) for item in facts_list):
        raise StudioError("fact sheet facts must be a list of strings")
    commands: list[dict[str, Any]] = []
    for index, item in enumerate(raw.get("commands") or []):
        if not isinstance(item, dict):
            raise StudioError(f"fact sheet commands entry {index + 1} must be an object")
        cmd_id = item.get("id")
        if not isinstance(cmd_id, str) or not cmd_id.strip():
            raise StudioError(f"fact sheet commands entry {index + 1} needs a non-empty id")
        argv = item.get("argv")
        if not isinstance(argv, list) or not argv or any(not isinstance(part, str) or not part for part in argv):
            raise StudioError(f"fact sheet command {cmd_id!r} needs a non-empty argv list of strings")
        entry: dict[str, Any] = {"id": cmd_id.strip(), "argv": list(argv)}
        if "shows" in item and item["shows"] is not None:
            if not isinstance(item["shows"], str):
                raise StudioError(f"fact sheet command {cmd_id!r} shows must be a string")
            entry["shows"] = item["shows"]
        if item.get("display") is not None:
            if not isinstance(item["display"], str):
                raise StudioError(f"fact sheet command {cmd_id!r} display must be a string")
            entry["display"] = item["display"]
        if "cwd" in item and item["cwd"] is not None:
            if not isinstance(item["cwd"], str):
                raise StudioError(f"fact sheet command {cmd_id!r} cwd must be a string")
            entry["cwd"] = item["cwd"]
        commands.append(entry)
    pages: list[dict[str, Any]] = []
    for index, item in enumerate(raw.get("pages") or []):
        if not isinstance(item, dict):
            raise StudioError(f"fact sheet pages entry {index + 1} must be an object")
        page_id = item.get("id")
        if not isinstance(page_id, str) or not page_id.strip():
            raise StudioError(f"fact sheet pages entry {index + 1} needs a non-empty id")
        url = item.get("url")
        if not isinstance(url, str) or not url.strip():
            raise StudioError(f"fact sheet page {page_id!r} needs a url string")
        entry = {"id": page_id.strip(), "url": url.strip()}
        if "shows" in item and item["shows"] is not None:
            if not isinstance(item["shows"], str):
                raise StudioError(f"fact sheet page {page_id!r} shows must be a string")
            entry["shows"] = item["shows"]
        pages.append(entry)
    seen: set[str] = set()
    for item in commands + pages:
        if item["id"] in seen:
            raise StudioError(f"fact sheet id {item['id']!r} is used more than once")
        seen.add(item["id"])
    return {
        "product": product.strip(),
        "summary": summary.strip(),
        "facts": facts_list,
        "commands": commands,
        "pages": pages,
    }


def _facts_lookup(facts: dict[str, Any]) -> dict[str, dict[str, Any]]:
    lookup: dict[str, dict[str, Any]] = {}
    for item in facts.get("commands") or []:
        lookup[item["id"]] = {"kind": "command", **item}
    for item in facts.get("pages") or []:
        lookup[item["id"]] = {"kind": "page", **item}
    return lookup


def script_prompt(brief: str, seconds: int, facts: dict[str, Any] | None = None) -> str:
    if facts is None:
        return _SCRIPT.format(seconds=seconds, brief=brief, **script_budget(seconds))
    lines = [f"- {item['id']}: {item.get('shows', item['id'])}" for item in facts.get("commands") or []]
    lines += [f"- {item['id']}: {item.get('shows', item['id'])}" for item in facts.get("pages") or []]
    facts_block = "\n".join(f"- {line}" for line in facts.get("facts") or []) or "- (none listed)"
    return _SCRIPT_FACTS.format(
        seconds=seconds,
        brief=brief,
        **script_budget(seconds),
        product=facts["product"],
        summary=facts["summary"],
        facts_block=facts_block,
        capture_list="\n".join(lines) or "- (none)",
    )


def plan_from(data: dict[str, Any], seconds: int, facts: dict[str, Any] | None = None) -> tuple[str, str, str, list[Shot]]:
    lookup = _facts_lookup(facts) if facts else {}
    shots = []
    for raw in data.get("shots") or []:
        if not isinstance(raw, dict):
            continue
        source = str(raw.get("source", "generate")).strip() or "generate"
        try:
            length = max(1, min(20, int(round(float(raw.get("seconds", 4))))))
        except (TypeError, ValueError):
            length = 4
        caption = str(raw.get("caption", "")).strip()
        if source == "capture":
            if facts is None:
                raise StudioError("capture shots need a fact sheet (--facts)")
            ref = raw.get("ref")
            if not isinstance(ref, str) or not ref.strip():
                continue
            ref = ref.strip()
            item = lookup.get(ref)
            if item is None:
                raise StudioError(f"capture ref {ref!r} is not in the fact sheet")
            visual = str(raw.get("visual", "")).strip() or str(item.get("shows") or ref)
            shots.append(Shot(length, visual, caption, source="capture", ref=ref))
        elif source == "generate":
            if not str(raw.get("visual", "")).strip():
                continue
            shots.append(Shot(length, str(raw["visual"]).strip(), caption, source="generate"))
        else:
            if not str(raw.get("visual", "")).strip():
                continue
            shots.append(Shot(length, str(raw["visual"]).strip(), caption))
    if not shots:
        raise StudioError("the script has no shots")
    total = sum(s.seconds for s in shots)
    if seconds and abs(total - seconds) > max(2, seconds // 10):  # stretch or shrink to the asked length
        scale = seconds / total
        for shot in shots:
            shot.seconds = max(1, round(shot.seconds * scale))
        shots[-1].seconds = max(1, shots[-1].seconds + seconds - sum(s.seconds for s in shots))
    return str(data.get("title", "")).strip(), str(data.get("voiceover", "")).strip(), str(data.get("music", "")).strip(), shots


def beats_from(data: dict[str, Any], facts: dict[str, Any] | None = None) -> list[dict[str, Any]]:
    """The storyboard rows from a model's beats plan, checked before anything is spent on them.

    A base with a prompt is generated, a base with a ref is real footage from the fact sheet, and a beat with
    neither stands on a moving background. Everything else is checked the way the storyboard and the motion
    graphics will read it, so a bad plan stops here, not after the pictures and the voice are paid for."""
    lookup = _facts_lookup(facts) if facts else {}
    rows = data.get("beats")
    if not isinstance(rows, list) or not rows or not all(isinstance(r, dict) for r in rows):
        raise StudioError("the script has no beats")
    out = []
    for number, raw in enumerate(rows, start=1):
        row = {k: v for k, v in raw.items() if k in ("say", "layers", "sounds", "cut", "energy", "hold")}
        base = raw.get("base") or {}
        if not isinstance(base, dict):
            raise StudioError(f"beat {number}: base must be an object with a prompt or a ref")
        if isinstance(base.get("ref"), str) and base["ref"].strip():
            if base["ref"].strip() not in lookup:
                raise StudioError(f"beat {number}: footage ref {base['ref'].strip()!r} is not in the fact sheet")
            row["base"] = {"kind": "capture", "ref": base["ref"].strip()}
        elif isinstance(base.get("prompt"), str) and base["prompt"].strip():
            row["base"] = {"kind": "generate", "prompt": base["prompt"].strip()}
        else:
            row["base"] = {"kind": "living"}
        out.append(row)
    dry = [{**row, "base": {"kind": "living"}} for row in out]
    try:
        beats = storyboard.parse(dry, Path.cwd())
        for beat in beats:
            layers = [{**lay, "at": 0, **({"until": 1} if "until" in lay else {})} for lay in beat.layers]
            motion.check_scene({"size": [64, 64], "seconds": 1, "layers": layers})
    except storyboard.StoryboardError as exc:
        raise StudioError(str(exc)) from exc
    except motion.MotionError as exc:
        raise StudioError(f"beat {beat.number}: {exc}") from exc
    return out


def script_problems(data: dict[str, Any], facts: dict[str, Any] | None = None) -> list[str]:
    """Every problem in a beats plan, each named by its beat and layer or sound, so one fix can mend them all.

    The check that runs before anything is spent stops at the first problem; a script writer told only that one
    mends it and trips on the next, so this checks each beat, and each overlay and sound in it, on its own."""
    rows = data.get("beats")
    if not isinstance(rows, list) or not rows or not all(isinstance(r, dict) for r in rows):
        return []
    found: list[str] = []
    for number, raw in enumerate(rows, start=1):
        bare = {k: v for k, v in raw.items() if k not in ("layers", "sounds")}
        try:
            beats_from({"beats": [bare]}, facts)
        except StudioError as exc:
            found.append(re.sub(r"^beat \d+:", f"beat {number}:", str(exc)))
            continue
        for key in ("layers", "sounds"):
            items = raw.get(key)
            if items is None:
                continue
            if not isinstance(items, list):
                try:
                    beats_from({"beats": [{**bare, key: items}]}, facts)
                except StudioError as exc:
                    found.append(re.sub(r"^beat \d+:", f"beat {number}:", str(exc)))
                continue
            for i, item in enumerate(items, start=1):
                try:
                    beats_from({"beats": [{**bare, key: [item]}]}, facts)
                except StudioError as exc:
                    said = re.sub(r"^(layer|sound)s?( \d+)?:? ?", "", re.sub(r"^beat \d+: ", "", str(exc)))
                    found.append(f"beat {number}: {key[:-1]} {i} {said}")
    return found


def untime_unreadable(data: dict[str, Any], facts: dict[str, Any] | None = None) -> tuple[dict[str, Any], list[str]]:
    """The beats plan with each overlay or sound time that cannot be read taken out, and a note for each.

    Used only once the script writer has had all its chances to fix them, so one garbled time never costs the
    whole film: the overlay or sound stays and plays at its default moment. Anything else that is wrong (a layer
    the engine cannot draw, a broken beat) is left as it is, so it stays a failure."""
    rows = data.get("beats")
    if not isinstance(rows, list):
        return data, []
    dropped: list[str] = []
    out: list[Any] = []
    for number, raw in enumerate(rows, start=1):
        if not isinstance(raw, dict):
            return data, []
        bare = {k: v for k, v in raw.items() if k not in ("layers", "sounds")}
        try:
            beats_from({"beats": [bare]}, facts)
        except StudioError:
            return data, []
        row = dict(raw)
        for key in ("layers", "sounds"):
            if not isinstance(raw.get(key), list):
                continue
            keep = []
            for i, item in enumerate(raw[key], start=1):
                try:
                    beats_from({"beats": [{**bare, key: [item]}]}, facts)
                except StudioError:
                    plain = {k: v for k, v in item.items() if k not in ("at", "until")} if isinstance(item, dict) else item
                    try:
                        beats_from({"beats": [{**bare, key: [plain]}]}, facts)
                    except StudioError:
                        return data, []  # not a timing problem
                    times = ", ".join(repr(item[k]) for k in ("at", "until") if k in item)
                    dropped.append(f"beat {number} {key[:-1]} {i} time {times}")
                    item = plain
                keep.append(item)
            row[key] = keep
        out.append(row)
    return {**data, "beats": out}, dropped


def srt(shots: list[Shot]) -> str:
    def stamp(t: int) -> str:
        return f"{t // 3600:02d}:{t // 60 % 60:02d}:{t % 60:02d},000"

    blocks, start = [], 0
    for index, shot in enumerate(shots, start=1):
        if shot.caption:
            blocks.append(f"{index}\n{stamp(start)} --> {stamp(start + shot.seconds)}\n{shot.caption}\n")
        start += shot.seconds
    return "\n".join(blocks)


IMAGE_ZOOM = 0.12
STILL_ZOOM = 0.10
STILL_FIT = 1 / (1 + STILL_ZOOM)  # a capture is shown this big, so the camera at its closest still has all of it in view
MAX_HOLD = 3.0  # a picture that stays frozen this long (seconds) is a slideshow, not a film
# Something happens: a patch of the picture (1/40 by 1/22 of the frame) changes sharply between two looks 0.1 s apart,
# as when a title lands, a cut lands or a hand moves. A slow camera drift over a still never counts.
EVENT_LEVEL = 16  # mean brightness change of one patch, 0-255, that counts as something happening
MAX_QUIET = 3.0  # seconds a film may go with nothing happening
MIN_LIVELY = 0.85  # share of the film's one-second windows in which something happens

# how the camera moves on a capture: (zooms in?, sideways lean 0..1, vertical lean 0..1); neighbouring shots differ
_CAMERA_MOVES = ((True, 0.5, 0.5), (False, 0.5, 0.5), (True, 0.0, 0.3), (False, 1.0, 0.7))


def _eased_zoom(extra: float, frames: int, closer: bool) -> str:
    """Zoom between 1 and 1+extra over the whole shot, easing in and out so the move never stops short."""
    last = max(1, frames - 1)
    sign = "-" if closer else "+"
    return f"1+{extra}*(0.5{sign}0.5*cos(PI*on/{last}))"


def shot_command(source: Path, kind: str, seconds: float, size: tuple[int, int], out: Path, variant: int = 0) -> list[str]:
    """Cut one shot to length. Stills and images get a camera move that lasts the whole shot (`variant` picks which)."""
    w, h = size
    frames = round(seconds * FPS)
    head = ["ffmpeg", "-y", "-loglevel", "error"]
    tail = ["-c:v", "libx264", "-preset", "veryfast", "-an", str(out)]
    if kind == "still":
        # A real capture is never cropped. It sits on a soft, darkened copy of itself that fills the frame, and the
        # camera moves over that: in, out, or drifting to a side, always keeping the whole capture in view.
        closer, lean_x, lean_y = _CAMERA_MOVES[variant % len(_CAMERA_MOVES)]
        fit_w, fit_h = int(2 * w * STILL_FIT) // 2 * 2, int(2 * h * STILL_FIT) // 2 * 2
        small_w, small_h = max(2, w // 8 * 2), max(2, h // 8 * 2)
        total = f"(1+{STILL_ZOOM})"
        # the window may lean toward a side only as far as it still holds the whole capture
        def lean(size_name: str, window: str, lean_by: float) -> str:
            fg = f"({size_name}/{total})"
            lo = f"max(0,({size_name}-{fg})/2+{fg}-{window})"
            hi = f"min(({size_name}-{fg})/2,{size_name}-{window})"
            return f"{lo}+{lean_by}*({hi}-({lo}))"
        graph = (f"[0:v]split=2[bg][fg];"
                 f"[bg]scale={small_w}:{small_h}:force_original_aspect_ratio=increase,crop={small_w}:{small_h},boxblur=6:2,"
                 f"scale={2 * w}:{2 * h},eq=brightness=-0.28:saturation=0.85[back];"
                 f"[fg]scale={fit_w}:{fit_h}:force_original_aspect_ratio=decrease[front];"
                 f"[back][front]overlay=(W-w)/2:(H-h)/2,format=rgb24,"
                 f"zoompan=z='{_eased_zoom(STILL_ZOOM, frames, closer)}':x='{lean('iw', 'iw/zoom', lean_x)}':"
                 f"y='{lean('ih', 'ih/zoom', lean_y)}':d={frames}:s={w}x{h}:fps={FPS},format=yuv420p[v]")
        return head + ["-i", str(source), "-filter_complex", graph, "-map", "[v]", "-frames:v", str(frames)] + tail
    if kind == "image":
        vf = (f"scale={2 * w}:{2 * h}:force_original_aspect_ratio=increase,crop={2 * w}:{2 * h},"
              f"zoompan=z='{_eased_zoom(IMAGE_ZOOM, frames, variant % 2 == 0)}':x='iw/2-(iw/zoom/2)':y='ih/2-(ih/zoom/2)':"
              f"d={frames}:s={w}x{h}:fps={FPS},format=yuv420p")
        return head + ["-i", str(source), "-vf", vf, "-frames:v", str(frames)] + tail
    vf = f"scale={w}:{h}:force_original_aspect_ratio=increase,crop={w}:{h},fps={FPS},format=yuv420p"
    return ["ffmpeg", "-y", "-loglevel", "error", "-stream_loop", "-1", "-i", str(source), "-t", str(seconds), "-vf", vf,
            "-c:v", "libx264", "-preset", "veryfast", "-an", str(out)]


def caption_style(size: tuple[int, int]) -> str:
    """Caption style sized from the short side of the frame, so tall formats do not get oversized text.

    Captions are laid out on a 288-line grid that is stretched to the frame height, so sizes are given on that grid.
    """
    w, h = size
    grid = 288 / h
    short = min(w, h)
    return f"Fontsize={round(short * 0.07 * grid, 1)},Outline={max(1.5, round(short * 0.006 * grid, 1))},Shadow=1,MarginV=40"


DISSOLVE = 0.5
LOUDNESS = "loudnorm=I=-16:TP=-1.5:LRA=9,aresample=48000"
MIN_TITLE = 1.0  # a title on screen for less than this (seconds) cannot be read, so it is left out


def title_track(shots: list[Shot], size: tuple[int, int], dissolve: float) -> str:
    """Animated on-screen words, one title per shot: they slide up and grow in once the shot has taken over, then fade out.

    Written as an ASS subtitle file laid out on the frame's own pixel grid, so it fits every format.
    """
    w, h = size
    short = min(w, h)
    font, pad = round(short * 0.05), round(short * 0.013)
    left, base = round(w * 0.05), h - round(h * 0.08)
    drop = round(h * 0.035)

    def stamp(t: float) -> str:
        cs = round(t * 100)
        return f"{cs // 360000}:{cs // 6000 % 60:02d}:{cs // 100 % 60:02d}.{cs % 100:02d}"

    lines = [
        "[Script Info]", "ScriptType: v4.00+", f"PlayResX: {w}", f"PlayResY: {h}", "WrapStyle: 0", "ScaledBorderAndShadow: yes", "",
        "[V4+ Styles]",
        "Format: Name,Fontname,Fontsize,PrimaryColour,SecondaryColour,OutlineColour,BackColour,Bold,Italic,Underline,StrikeOut,"
        "ScaleX,ScaleY,Spacing,Angle,BorderStyle,Outline,Shadow,Alignment,MarginL,MarginR,MarginV,Encoding",
        f"Style: Title,Arial,{font},&H00FFFFFF,&H00FFFFFF,&H99140F0D,&H99140F0D,1,0,0,0,100,100,0,0,3,{pad},0,1,{left},{left},{base},1",
        "", "[Events]", "Format: Layer,Start,End,Style,Name,MarginL,MarginR,MarginV,Effect,Text",
    ]
    start = 0.0
    for shot in shots:
        end = start + shot.seconds
        words = re.sub(r"\{[^}]*\}", "", shot.caption or "")
        words = " ".join(re.sub(r"[{}\\]", "", words).split())
        on, off = start + dissolve + 0.1, end - dissolve
        if words and off - on >= MIN_TITLE:
            move = f"\\move({left},{base + drop},{left},{base},0,350)"
            grow = "\\fscx92\\fscy92\\t(0,350,\\fscx100\\fscy100)"
            lines.append(f"Dialogue: 0,{stamp(on)},{stamp(off)},Title,,0,0,0,,{{\\fad(300,350){move}{grow}}}{words}")
        start = end
    return "\n".join(lines) + "\n"


def dissolve_length(shots: list[Shot]) -> float:
    """How long neighbouring shots overlap: half a second, less when a shot is too short to give that much."""
    if len(shots) < 2:
        return 0.0
    return min(DISSOLVE, min(s.seconds for s in shots) / 2)


def join_command(clips: list[Path], seconds: list[int], dissolve: float, out: Path) -> list[str]:
    """Join the shots with dissolves; the film keeps the length of the shots added up, so the captions stay on time."""
    cmd = ["ffmpeg", "-y", "-loglevel", "error"]
    for clip in clips:
        cmd += ["-i", str(clip)]
    graph, label, start = [], "[0:v]", seconds[0]
    for index in range(1, len(clips)):
        last = index == len(clips) - 1
        graph.append(f"{label}[{index}:v]xfade=transition=fade:duration={dissolve}:offset={round(start - dissolve, 3)}"
                     f"[{'v' if last else f'x{index}'}]")
        label = f"[x{index}]"
        start += seconds[index]
    return cmd + ["-filter_complex", ";".join(graph), "-map", "[v]", "-c:v", "libx264", "-preset", "veryfast",
                  "-crf", "14", "-pix_fmt", "yuv420p", str(out)]


def final_command(joined: Path, voice: Path | None, music: Path | None, total: int, captions: bool, out: Path,
                  size: tuple[int, int] = (1920, 1080), titles: bool = False) -> list[str]:
    """Fade the picture and sound in and out; clean the voice, dip the music under it, level the mix.

    `captions` burns in captions.srt and `titles` the animated words in titles.ass, both read from the working folder.
    """
    cmd = ["ffmpeg", "-y", "-loglevel", "error", "-i", str(joined)]
    inputs = []
    if voice:
        cmd += ["-i", str(voice)]
        inputs.append("voice")
    if music:
        cmd += ["-stream_loop", "-1", "-i", str(music)]
        inputs.append("music")
    edge = round(min(0.5, total / 6), 3)
    fades = f"fade=t=in:st=0:d={edge},fade=t=out:st={round(total - edge, 3)}:d={edge}"
    picture = f"subtitles=captions.srt:force_style='{caption_style(size)}'," if captions else ""
    picture += "subtitles=titles.ass," if titles else ""
    picture += fades
    graph = []
    labels = []
    for index, name in enumerate(inputs, start=1):
        fit = f"apad=whole_dur={total},atrim=0:{total}"
        if name == "voice":
            graph.append(f"[{index}:a]highpass=f=80,acompressor=threshold=-18dB:ratio=3:attack=5:release=120,{fit}[voice]")
        else:
            graph.append(f"[{index}:a]volume={0.6 if voice else 1.0},{fit}[music]")
        labels.append(f"[{name}]")
    if len(labels) == 2:
        graph.append("[voice]asplit=2[voice_mix][voice_key]")
        graph.append("[music][voice_key]sidechaincompress=threshold=0.03:ratio=6:attack=25:release=450:makeup=1[ducked]")
        graph.append("[voice_mix][ducked]amix=inputs=2:duration=first:normalize=0[mixed]")
        labels = ["[mixed]"]
    if labels:
        graph.append(f"{labels[0]}{LOUDNESS},afade=t=out:st={round(total - edge, 3)}:d={edge}[a]")
    if graph or captions or titles:
        graph.insert(0, f"[0:v]{picture}[v]")
        cmd += ["-filter_complex", ";".join(graph), "-map", "[v]"]
    else:
        cmd += ["-vf", picture, "-map", "0:v"]
    if labels:
        cmd += ["-map", "[a]", "-c:a", "aac", "-b:a", "192k"]
    cmd += ["-c:v", "libx264", "-preset", "veryfast", "-crf", "20", "-pix_fmt", "yuv420p", "-t", str(total),
            "-movflags", "+faststart", str(out)]
    return cmd


def probe(path: Path) -> dict[str, Any]:
    run = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration:stream=codec_type,width,height",
                          "-of", "json", str(path)], capture_output=True, text=True, check=False)
    data = json.loads(run.stdout or "{}")
    video = next((s for s in data.get("streams", []) if s.get("codec_type") == "video"), {})
    return {"seconds": float(data.get("format", {}).get("duration", 0) or 0), "width": video.get("width"),
            "height": video.get("height"), "audio": any(s.get("codec_type") == "audio" for s in data.get("streams", []))}


def convert(args: list[str]) -> bool:
    """Run FFmpeg once on local files (a still resized, a sound re-encoded); True when it finished."""
    if shutil.which("ffmpeg") is None:
        return False
    return subprocess.run(["ffmpeg", "-y", "-loglevel", "error", *args], capture_output=True, check=False).returncode == 0


def frozen_stretches(path: Path) -> list[tuple[float, float]]:
    """Every stretch of a film where the picture does not change for a second or more, as (start, seconds)."""
    run = subprocess.run(["ffmpeg", "-hide_banner", "-nostats", "-i", str(path), "-map", "0:v:0", "-vf",
                          "freezedetect=n=-50dB:d=1", "-f", "null", "-"], capture_output=True, text=True, check=False)
    starts = [float(m) for m in re.findall(r"freeze_start: ([0-9.]+)", run.stderr)]
    lengths = [float(m) for m in re.findall(r"freeze_duration: ([0-9.]+)", run.stderr)]
    return list(zip(starts, lengths))


def picture_activity(path: Path) -> dict[str, float]:
    """How often something happens on screen: the longest quiet stretch (seconds, and where it starts) and the
    share of the film's seconds in which something happens. Looks ten times a second, at patches of the frame."""
    cols, rows = 40, 22
    run = subprocess.run(["ffmpeg", "-v", "error", "-i", str(path), "-map", "0:v:0", "-vf",
                          f"fps=10,scale=320:180,format=gray,tblend=all_mode=difference,scale={cols}:{rows}:flags=area",
                          "-f", "rawvideo", "-pix_fmt", "gray", "-"], capture_output=True, check=False)
    raw, step = run.stdout, cols * rows
    events = [max(raw[i:i + step]) > EVENT_LEVEL for i in range(0, len(raw) - step + 1, step)]
    if not events:  # FFmpeg could not read the picture, so nothing was seen to happen
        return {"longest_quiet": math.inf, "quiet_from": 0.0, "lively_share": 0.0}
    quiet = longest = longest_at = 0
    for index, event in enumerate(events):
        quiet = 0 if event else quiet + 1
        if quiet > longest:
            longest, longest_at = quiet, index + 1 - quiet
    # every one-second window, sliding a tenth at a time, so where the film's seconds happen to start never matters
    seconds = [any(events[i:i + 10]) for i in range(max(1, len(events) - 9))]
    return {"longest_quiet": longest / 10, "quiet_from": longest_at / 10, "lively_share": sum(seconds) / len(seconds)}


SHEET_ACROSS, SHEET_DOWN = 4, 3
SHEET_MAX_SIDE = 1024  # the largest picture the spend gate will count (spend.PICTURE_MAX_SIDE)


def _even(value: float) -> int:
    return max(2, int(value) // 2 * 2)


def contact_sheet(path: Path, out: Path, *, kind: str) -> Path | None:
    """One small JPEG the judge can look at: for a film, twelve moments spread across it in a 4 x 3 grid; for a
    picture, the picture itself made to fit. At most SHEET_MAX_SIDE a side. None when FFmpeg cannot read the file."""
    facts = probe(path) if shutil.which("ffprobe") else {}
    width, height = facts.get("width"), facts.get("height")
    if not width or not height:
        return None
    out.unlink(missing_ok=True)
    if kind == "video":
        seconds = facts.get("seconds") or 0
        if seconds <= 0:
            return None
        frames = SHEET_ACROSS * SHEET_DOWN
        tile_w = min(SHEET_MAX_SIDE / SHEET_ACROSS, SHEET_MAX_SIDE / SHEET_DOWN * width / height)
        tile_w, tile_h = _even(tile_w), _even(tile_w * height / width)
        args = ["-ss", f"{seconds / (2 * frames):.3f}", "-i", str(path), "-map", "0:v:0", "-vf",
                f"fps={frames}/{seconds:.3f},scale={tile_w}:{tile_h},setsar=1,tile={SHEET_ACROSS}x{SHEET_DOWN}",
                "-frames:v", "1", "-q:v", "4", str(out)]
    else:
        scale = min(1.0, SHEET_MAX_SIDE / max(width, height))
        args = ["-i", str(path), "-vf", f"scale={max(1, round(width * scale))}:{max(1, round(height * scale))},setsar=1",
                "-frames:v", "1", "-q:v", "3", str(out)]
    if not convert(args) or not out.is_file() or out.stat().st_size == 0:
        return None
    return out


def data_url(path: Path) -> str:
    """A JPEG or PNG as an inline picture a model can be sent."""
    kind = "png" if path.suffix.lower() == ".png" else "jpeg"
    return f"data:image/{kind};base64," + base64.b64encode(path.read_bytes()).decode("ascii")


def sound_facts(path: Path) -> dict[str, float] | None:
    """What the sound is like, measured: integrated loudness (LUFS), true peak (dBFS), length, and the share of it
    that is silent (below -45 dB for half a second or more). None when there is no sound FFmpeg can read."""
    if shutil.which("ffmpeg") is None or not probe(path).get("audio"):
        return None
    run = subprocess.run(["ffmpeg", "-hide_banner", "-nostats", "-i", str(path), "-map", "0:a:0", "-af",
                          "ebur128=peak=true,silencedetect=n=-45dB:d=0.5", "-f", "null", "-"],
                         capture_output=True, text=True, check=False)
    summary = run.stderr.rpartition("Summary:")[2]
    loud = re.search(r"I:\s+(-?[0-9.]+|-inf) LUFS", summary)
    peak = re.search(r"Peak:\s+(-?[0-9.]+|-inf) dBFS", summary)
    if run.returncode != 0 or loud is None or peak is None:
        return None
    seconds = probe(path)["seconds"] or 0.0
    starts = [float(m) for m in re.findall(r"silence_start: (-?[0-9.]+)", run.stderr)]
    lengths = [float(m) for m in re.findall(r"silence_duration: ([0-9.]+)", run.stderr)]
    silent = sum(lengths) + sum(max(0.0, seconds - start) for start in starts[len(lengths):])
    return {"loudness_lufs": float(loud.group(1)), "peak_dbfs": float(peak.group(1)), "seconds": round(seconds, 2),
            "silent_share": round(min(1.0, silent / seconds), 3) if seconds else 1.0}


def _render_checks(name: str, final: Path, total: float, size: tuple[int, int], sound: bool,
                   tolerance: float) -> list[dict[str, Any]]:
    """Measure one finished render: its length, frame size, sound, that the picture never stands still, and
    that something keeps happening on screen."""
    measured = probe(final)
    holds = frozen_stretches(final)
    longest = max(holds, key=lambda stretch: stretch[1], default=None)
    still = longest is not None and longest[1] >= MAX_HOLD
    activity = picture_activity(final)
    return [
        {"render": name, "check": "length", "ok": abs(measured["seconds"] - total) <= tolerance,
         "detail": f"{measured['seconds']:.1f}s of {total:g}s"},
        {"render": name, "check": "frame size", "ok": (measured["width"], measured["height"]) == size,
         "detail": f"{measured['width']}x{measured['height']}"},
        {"render": name, "check": "sound", "ok": measured["audio"] == sound,
         "detail": "voice/music present" if measured["audio"] else "silent"},
        {"render": name, "check": "picture keeps moving", "ok": not still,
         "detail": (f"holds still for {longest[1]:.1f}s from {longest[0]:.1f}s" if still else
                    f"never holds still for {MAX_HOLD:g}s or more")},
        {"render": name, "check": "something happens", "ok": activity["longest_quiet"] <= MAX_QUIET,
         "detail": (f"nothing new on screen for {activity['longest_quiet']:.1f}s from {activity['quiet_from']:.1f}s "
                    f"({MAX_QUIET:g}s at most)" if math.isfinite(activity["longest_quiet"])
                    else "the picture could not be read")},
        {"render": name, "check": "picture changes every second", "ok": activity["lively_share"] >= MIN_LIVELY,
         "detail": f"something happens in {activity['lively_share']:.0%} of its seconds ({MIN_LIVELY:.0%} at least)"},
    ]


def _run(cmd: list[str], cwd: Path, production: Production) -> None:
    production.commands.append(cmd)
    done = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, check=False)
    if done.returncode != 0:
        raise StudioError(f"ffmpeg failed: {(done.stderr or '').strip()[-400:]}")


def _spoken_guess(board: list[dict[str, Any]], rate: float = FAST_RATE) -> float:
    """How long the storyboard runs if every phrase is read at ``rate`` words a second."""
    beats = storyboard.parse([{**row, "base": {"kind": "living"}} for row in board], Path.cwd())
    for beat in beats:
        for phrase in beat.phrases:
            phrase.seconds = len(phrase.text.split()) / rate
    return storyboard.time_beats(beats)


def produce(
    brief: str,
    *,
    provider_id: str,
    model: str,
    visual_provider: str = "",
    visual_model: str = "",
    visual_kind: str = "image",
    voice_provider: str | None = None,
    voice_model: str | None = None,
    voice: str | None = None,
    music_provider: str | None = None,
    music_model: str | None = None,
    music_file: Path | None = None,
    seconds: int = 30,
    formats: tuple[str, ...] = ("16x9", "9x16", "1x1"),
    captions: bool = True,
    max_cost_usd: str | None = None,
    out_dir: Path,
    size_scale: float = 1.0,
    text_transport: live.Transport | None = None,
    media_transport: Any = None,
    media_get: Any = None,
    facts: dict[str, Any] | None = None,
    allow_commands: bool = False,
) -> Production:
    for tool in ("ffmpeg", "ffprobe"):
        if shutil.which(tool) is None:
            raise StudioError(f"{tool} is not installed; install FFmpeg (https://ffmpeg.org) and try again")
    if visual_kind not in ("image", "video"):
        raise StudioError("--visual-kind must be image or video")
    unknown = [f for f in formats if f not in FORMATS]
    if unknown:
        raise StudioError(f"unknown format {', '.join(unknown)}; use {', '.join(FORMATS)}")
    if not 3 <= seconds <= 600:
        raise StudioError("--seconds must be 3 to 600")
    paid = [p for p in (providers.find(provider_id),) if p is not None and not p.local]
    for service in (voice_provider, music_provider):
        found = media.find(service) if service else None
        if found is not None and not found.local:
            paid.append(found)
    if visual_provider:
        found = media.find(visual_provider)
        if found is not None and not found.local:
            paid.append(found)
    if paid and max_cost_usd is None:
        raise StudioError("name one spending limit for the whole video (--max-cost-usd)")
    budget = _Budget(max_cost_usd)
    out_dir = out_dir.resolve()  # FFmpeg runs inside this folder, so every path in it must be absolute
    out_dir.mkdir(parents=True, exist_ok=False)
    production = Production(out_dir)

    def record(role: str, result: Any, figure: Any) -> None:
        production.calls.append({"role": role, "status": result.status, "code": result.code, "usd": figure})
        if result.status == "refused" and result.code == "PHC-COST-0001":
            raise StudioError("spending limit reached")
        if result.status != "success":
            raise StudioError(f"{role}: {result.message}")

    try:
        lookup = _facts_lookup(facts) if facts else {}

        def make_media(kind: str, service: str, model_id: str, prompt: str, target: Path, params: dict[str, Any]) -> str:
            result = media.generate(kind, service, model_id, prompt=prompt, out=target, params=params,
                                    max_cost_usd=budget.next_limit(), transport=media_transport, get=media_get)
            figure = (result.cost or {}).get("usd")
            if result.status != "refused":
                budget.charge(figure)
            record(f"{kind}: {prompt[:40]}", result, figure)
            return str(result.path)

        def capture_still(ref: str | None, target: Path) -> str:
            item = lookup.get(ref or "")
            if item is None:
                raise StudioError(f"capture ref {ref!r} is not in the fact sheet")
            try:
                if item["kind"] == "command":
                    if not allow_commands:
                        raise StudioError(
                            "command capture shots need --allow-commands (running the commands in the fact sheet on this machine)"
                        )
                    cwd = Path(item["cwd"]) if item.get("cwd") else Path.cwd()
                    output = capture.run_command(item["argv"], cwd=cwd)
                    cmd_line = item.get("display") or " ".join(item["argv"])
                    return str(capture.render_card(cmd_line, output, target.with_suffix(".png"),
                                                   redact=capture.private_text()))
                return str(capture.render_page(item["url"], target.with_suffix(".png")))
            except capture.CaptureError as exc:
                raise StudioError(str(exc)) from exc

        def speak(text: str, name: str) -> Path:
            return Path(make_media("speech", voice_provider or "", voice_model or "", text, out_dir / "voice" / name,
                                   {"voice": voice} if voice else {}))

        too_long = 0

        def voice_board(board: list[dict[str, Any]]) -> tuple[list[storyboard.Beat], float, str | None]:
            """Speak the storyboard's words and time it. A film the chosen voice makes too long is a problem to send
            back, with that voice's own pace, and its spoken files are set aside so the next script starts fresh."""
            nonlocal too_long
            try:
                beats = storyboard.parse([{**row, "base": {"kind": "living"}} for row in board], out_dir)
                if any(b.phrases for b in beats):
                    storyboard.voice(beats, speak)
            except storyboard.StoryboardError as exc:
                raise StudioError(str(exc)) from exc
            total = storyboard.time_beats(beats)
            if total <= seconds + brief_slack(seconds):
                return beats, storyboard.fill_to(beats, seconds), None
            too_long += 1
            if (out_dir / "voice").is_dir():
                (out_dir / "voice").rename(out_dir / f"voice-too-long-{too_long}")
            words = sum(len(p.text.split()) for b in beats for p in b.phrases)
            talk = sum(p.seconds for b in beats for p in b.phrases)
            if not words:
                fit = script_budget(seconds)
                return beats, total, (f"the script is too long: its beats run {total:.1f} seconds, and the film must be "
                                      f"about {seconds} seconds. Use {fit['fewest']} to {fit['most']} beats")
            rate = words / talk
            return beats, total, (f"the script is too long: spoken by the chosen voice it runs {total:.1f} seconds, and "
                                  f"the film must be about {seconds} seconds. This voice speaks about {rate:.1f} words a "
                                  f"second, so use {script_budget(seconds, rate)['words']} words in all at most")

        task = script_prompt(brief, seconds, facts)
        prompt, role = task, "script"
        for attempt in range(1 + SCRIPT_FIXES):
            reply = live.run_prompt(provider_id, model, prompt=prompt, max_output_tokens=2048,
                                    max_cost_usd=budget.next_limit(), transport=text_transport, json_reply=True)
            figure = (reply.cost or {}).get("usd")
            budget.charge(figure if reply.status != "refused" else 0)
            record(role, reply, figure)
            reply_text = reply.output_text or ""
            board: list[dict[str, Any]] | None = None
            plan: tuple[str, str, str, list[Shot]] | None = None
            problem: str | None = None
            data: dict[str, Any] | None = None
            try:
                data = _json_object(reply_text)
                if "beats" in data or "shots" not in data:
                    board = beats_from(data, facts)
                    guess = _spoken_guess(board)
                    if guess > seconds + brief_slack(seconds):
                        fit = script_budget(seconds)
                        problem = (f"the script is too long: even read quickly it runs about {guess:.0f} seconds, and "
                                   f"the film must be about {seconds} seconds. Use {fit['fewest']} to {fit['most']} beats "
                                   f"and {fit['words']} words in all at most")
                else:
                    plan = plan_from(data, seconds, facts)
            except StudioError as exc:
                problem = str(exc)
                if data is not None and board is None and plan is None:
                    problem = "; ".join(script_problems(data, facts)) or problem  # all of them, not just the first
            if problem is not None and attempt == SCRIPT_FIXES and board is None and plan is None and data:
                cleaned, dropped = untime_unreadable(data, facts)  # the last chance is gone: keep what can be read
                if dropped:
                    try:
                        board = beats_from(cleaned, facts)
                    except StudioError:
                        pass
                    else:
                        data, problem = cleaned, None
                        production.checks.append({
                            "render": "all", "check": "unreadable timings dropped", "ok": True,
                            "detail": f"after {SCRIPT_FIXES} fixes these times still could not be read, so those parts "
                                      f"play at their default moment: {'; '.join(dropped)}"})
            if problem is None and board is not None:
                if any(row["base"]["kind"] == "generate" for row in board) and (not visual_provider or not visual_model):
                    raise StudioError("generated pictures need --visual-provider and --visual-model (see `proofhouse media list`)")
                if any(row.get("say") for row in board) and not voice_provider:
                    raise StudioError("a film with words needs a voice service to speak them (--voice-provider)")
                timed, length, problem = voice_board(board)
            if problem is None:
                break
            if attempt == SCRIPT_FIXES:  # keep what it said last, so the failure can be read
                (out_dir / "script-reply.txt").write_text(reply_text, encoding="utf-8")
                raise StudioError(f"{problem} (the script writer's last reply is in script-reply.txt); try another model")
            prompt, role = _FIX.format(problem=problem, task=task, reply=reply_text[:6000]), "script fix"

        if board is not None:
            production.title, production.music_brief = str(data.get("title", "")).strip(), str(data.get("music", "")).strip()
            script = {"title": production.title, "music": production.music_brief, "beats": board}
            for row, beat in zip(board, timed):  # keep the spoken files, so nothing is spoken twice
                if beat.phrases and row.pop("say", None) is not None:
                    row["phrases"] = [{"text": p.text, "file": Path(p.file).relative_to(out_dir).as_posix()}
                                      for p in beat.phrases]
            (out_dir / "script.json").write_text(json.dumps(script, indent=2) + "\n", encoding="utf-8")
            (out_dir / "shots").mkdir()
            for number, (row, beat) in enumerate(zip(board, timed), start=1):
                base, target = row["base"], out_dir / "shots" / f"beat-{number:02d}"
                if base["kind"] == "capture":
                    file = capture_still(base["ref"], target)
                    row["base"] = {"kind": "capture", "file": Path(file).relative_to(out_dir).as_posix()}
                elif base["kind"] == "generate":
                    params = ({"seconds": max(2, min(10, math.ceil(beat.frames / beat.fps)))} if visual_kind == "video"
                              else {"size": "1792x1024"})
                    file = make_media(visual_kind, visual_provider, visual_model, base["prompt"], target, params)
                    row["base"] = {"kind": visual_kind, "file": Path(file).relative_to(out_dir).as_posix()}
            if music_file is not None:
                production.music_file = str(shutil.copy2(music_file, out_dir / f"music{music_file.suffix}"))
            elif music_provider and production.music_brief:
                production.music_file = make_media("music", music_provider, music_model or "", production.music_brief,
                                                   out_dir / "music", {"seconds": math.ceil(max(length, seconds))})

            production = assemble_beats(out_dir, script, formats=formats, size_scale=size_scale, captions=captions,
                                        speak=speak, music_file=production.music_file, production=production,
                                        seconds=seconds)
            (out_dir / "script.json").write_text(json.dumps(script, indent=2) + "\n", encoding="utf-8")
            production.spent_usd = budget.spent
            _write_record(production, brief)
            return production

        assert plan is not None
        title, narration, music_brief, shots = plan
        production.title, production.voiceover, production.music_brief, production.shots = title, narration, music_brief, shots
        (out_dir / "script.json").write_text(json.dumps({"title": title, "voiceover": narration, "music": music_brief,
                                                          "shots": [vars(s) for s in shots]}, indent=2) + "\n", encoding="utf-8")

        needs_generated = any(s.source == "generate" for s in shots)
        if needs_generated and (not visual_provider or not visual_model):
            raise StudioError("generated shots need --visual-provider and --visual-model (see `proofhouse media list`)")
        has_capture = any(s.source == "capture" for s in shots)
        assemble_kind = "mixed" if has_capture else visual_kind

        (out_dir / "shots").mkdir()
        for index, shot in enumerate(shots, start=1):
            target = out_dir / "shots" / f"shot-{index:02d}"
            if shot.source == "capture":
                shot.file = capture_still(shot.ref, target)
            else:
                params = {"seconds": shot.seconds} if visual_kind == "video" else {"size": "1792x1024"}
                shot.file = make_media(visual_kind, visual_provider, visual_model, shot.visual, target, params)
        if voice_provider and narration:
            production.voice_file = make_media("speech", voice_provider, voice_model or "", narration, out_dir / "voice",
                                               {"voice": voice} if voice else {})
        if music_file is not None:
            production.music_file = str(shutil.copy2(music_file, out_dir / f"music{music_file.suffix}"))
        elif music_provider and music_brief:
            production.music_file = make_media("music", music_provider, music_model or "", music_brief, out_dir / "music",
                                               {"seconds": sum(s.seconds for s in shots)})
    except StudioError as exc:
        production.stopped = str(exc)
        production.spent_usd = budget.spent
        _write_record(production, brief)
        return production

    production = assemble(
        out_dir, shots, visual_kind=assemble_kind, formats=formats, size_scale=size_scale, captions=captions,
        voice_file=production.voice_file, music_file=production.music_file, production=production,
    )
    production.spent_usd = budget.spent
    _write_record(production, brief)
    return production


_STILL_SUFFIXES = frozenset({".png", ".jpg", ".jpeg", ".webp", ".gif", ".bmp"})


VOICE_MARGIN = 0.5  # seconds of picture left after the last word
VOICE_FITS = 0.25  # a voice this much past the film's end still fits


def _fit_to_voice(shots: list[Shot], spoken: float) -> tuple[float, int]:
    """When the voice runs past the film, lengthen the shots a whole second at a time until it ends with a little
    picture left. Each second goes to the shot whose words are most crowded for its length. A voice that already
    fits is left alone. Returns the voice's length and the film's length before."""
    before = sum(s.seconds for s in shots)
    if spoken <= before + VOICE_FITS:
        return spoken, before
    while shots and sum(s.seconds for s in shots) < spoken + VOICE_MARGIN:
        crowded = max(shots, key=lambda s: (len(s.caption.split()) or 0.1) / max(s.seconds, 1))
        crowded.seconds += 1
    return spoken, before


def assemble(
    out_dir: Path,
    shots: list[Shot],
    *,
    visual_kind: str,
    formats: tuple[str, ...],
    size_scale: float = 1.0,
    captions: bool = True,
    voice_file: str | None = None,
    music_file: str | None = None,
    production: Production | None = None,
    titles: bool | None = None,
) -> Production:
    """Cut shots to length, join, mix audio, burn captions or animated titles, and measure each render.

    `titles` puts each shot's words on screen as animated titles. Left as None, they appear whenever captions are not burned in.
    """
    if production is None:
        production = Production(out_dir)
    else:
        production.folder = out_dir
    production.voice_file = voice_file
    production.music_file = music_file
    fitted = _fit_to_voice(shots, probe(Path(voice_file))["seconds"]) if voice_file else None
    total = sum(s.seconds for s in shots)
    (out_dir / "captions.srt").write_text(srt(shots), encoding="utf-8")
    has_captions = captions and any(s.caption for s in shots)
    has_titles = (not has_captions if titles is None else titles) and any(s.caption for s in shots)
    work = out_dir / "work"
    work.mkdir()
    try:
        if fitted is not None:
            spoken, before = fitted
            production.checks.append({
                "render": "all", "check": "voice fits the film", "ok": spoken <= total + VOICE_FITS,
                "detail": f"{spoken:.1f}s of voice in a {total}s film" + (
                    f"; the shots were lengthened from {before}s to {total}s to fit it" if total > before else "")})
        for name in formats:
            w, h = FORMATS[name]
            size = (int(w * size_scale) // 2 * 2, int(h * size_scale) // 2 * 2)
            clips = []
            dissolve = dissolve_length(shots)
            for index, shot in enumerate(shots, start=1):
                if not shot.file:
                    raise StudioError(f"shot {index} has no file")
                clip = work / f"{name}-shot-{index:02d}.mp4"
                kind = visual_kind
                if visual_kind == "mixed":
                    is_still = Path(shot.file).suffix.lower() in _STILL_SUFFIXES
                    kind = ("still" if shot.source == "capture" else "image") if is_still else "video"
                # every shot after the first starts one dissolve early, under the end of the shot before it
                _run(shot_command(Path(shot.file), kind, shot.seconds + (dissolve if index > 1 else 0), size, clip, index - 1),
                     out_dir, production)
                clips.append(clip)
            joined = work / f"{name}-joined.mp4"
            if len(clips) == 1:
                joined = clips[0]
            else:
                _run(join_command(clips, [s.seconds for s in shots], dissolve, joined), work, production)
            final = out_dir / f"video-{name}.mp4"
            if has_titles:
                (out_dir / "titles.ass").write_text(title_track(shots, size, dissolve), encoding="utf-8")
            _run(final_command(joined, Path(production.voice_file) if production.voice_file else None,
                               Path(production.music_file) if production.music_file else None, total, has_captions, final, size,
                               has_titles),
                 out_dir, production)
            production.renders[name] = str(final)
            production.checks += _render_checks(name, final, total, size, bool(production.voice_file or production.music_file),
                                                max(1.0, total * 0.05))
        production.checks.append({"render": "all", "check": "captions match the script",
                                  "ok": srt(shots) == (out_dir / "captions.srt").read_text(encoding="utf-8"),
                                  "detail": f"{sum(1 for s in shots if s.caption)} captions"})
    except StudioError as exc:
        production.stopped = str(exc)
    shutil.rmtree(work, ignore_errors=True)
    _set_aside_failed(production)
    return production


def _unvoiced(text: str, name: str) -> Path:
    raise StudioError(f"phrase {name} ({text[:40]!r}) has no voice file; give it one, or name a voice service to speak it")


def _beat_record(beat: storyboard.Beat, root: Path) -> dict[str, Any]:
    def name(path: Any) -> str | None:
        if not path:
            return None
        path = Path(path)
        return path.relative_to(root).as_posix() if path.is_relative_to(root) else path.name

    return {"beat": beat.number, "start": round(beat.start, 3), "seconds": round(beat.span, 3), "cut": beat.cut,
            "energy": beat.energy, "real": beat.real, "base": beat.base["kind"], "file": name(beat.base.get("file")),
            "phrases": [{"text": p.text, "start": round(p.start, 3), "seconds": round(p.seconds, 3), "file": name(p.file)}
                        for p in beat.phrases]}


def assemble_beats(
    out_dir: Path,
    board: Any,
    *,
    formats: tuple[str, ...],
    size_scale: float = 1.0,
    captions: bool = True,
    speak: Callable[[str, str], Path] | None = None,
    music_file: str | None = None,
    production: Production | None = None,
    seconds: float | None = None,
) -> Production:
    """Make a film from a storyboard of beats, every file in it named inside ``out_dir``.

    Each phrase is spoken (``speak(text, name)``, for phrases with no file) and measured, and the beats are timed to
    the words. Then, for each format, every beat's motion scene is rendered, the beats are joined with their
    transitions, the sound design is laid on its own track, music and sounds dip under every line, captions are
    burned in, and the render is measured. Given ``seconds``, a film shorter than that is held out to it, and
    its length is checked against it.
    """
    if production is None:
        production = Production(out_dir)
    else:
        production.folder = out_dir
    production.music_file = music_file
    work = out_dir / "work"
    work.mkdir()
    try:
        beats = storyboard.parse(board, out_dir)
        storyboard.voice(beats, speak or _unvoiced)
        total = storyboard.fill_to(beats, seconds) if seconds else storyboard.time_beats(beats)
        share = storyboard.check_mix(beats, total)
        production.beats = [_beat_record(b, out_dir) for b in beats]
        production.voiceover = " ".join(p.text for b in beats for p in b.phrases)
        spans = storyboard.speech_spans(beats)
        text = storyboard.captions(beats)
        (out_dir / "captions.srt").write_text(text, encoding="utf-8")
        voice_cmd = storyboard.voice_command(beats, total, out_dir / "voice.wav")
        if voice_cmd:
            _run(voice_cmd, out_dir, production)
            production.voice_file = str(out_dir / "voice.wav")
        for name in formats:
            w, h = FORMATS[name]
            size = (int(w * size_scale) // 2 * 2, int(h * size_scale) // 2 * 2)
            planned = storyboard.scenes(beats, size)
            clips = []
            for beat, sc in zip(beats, planned):
                clips.append(motion.render(sc, work / f"{name}-beat-{beat.number:02d}.mp4"))
            joined = clips[0]
            if len(clips) > 1:
                joined = work / f"{name}-joined.mp4"
                _run(storyboard.join_command(clips, beats, joined), work, production)
            effects = sound.mix(storyboard.sound_events(beats, planned), total, work / f"{name}-sounds.wav")
            final = out_dir / f"video-{name}.mp4"
            burn = f"subtitles=captions.srt:force_style='{caption_style(size)}'" if captions and text else ""
            _run(storyboard.mix_command(joined, Path(production.voice_file) if production.voice_file else None,
                                        Path(music_file) if music_file else None, effects, total, spans, final,
                                        loudness=LOUDNESS, picture_filter=burn), out_dir, production)
            production.renders[name] = str(final)
            production.checks += _render_checks(name, final, total, size, True, 0.1)
        last = max((p.start + p.seconds for b in beats for p in b.phrases), default=0.0)
        production.checks += [
            {"render": "all", "check": "voice fits the film", "ok": last <= total + 0.01,
             "detail": f"the last word ends at {last:.2f}s of a {total:.2f}s film" if last else "no words spoken"},
            {"render": "all", "check": "real footage share", "ok": share <= storyboard.REAL_SHARE + 1e-9,
             "detail": f"{share:.0%} of the film is real product footage (a third at most)"},
            {"render": "all", "check": "captions match the script",
             "ok": text == (out_dir / "captions.srt").read_text(encoding="utf-8"),
             "detail": f"{sum(len(b.phrases) for b in beats)} captions"},
        ]
        if seconds:
            production.checks.append({"render": "all", "check": "length matches the brief",
                                      "ok": abs(total - seconds) <= brief_slack(seconds),
                                      "detail": f"{total:.1f}s of the {seconds:g}s asked"})
    except (StudioError, storyboard.StoryboardError, motion.MotionError, sound.SoundError) as exc:
        production.stopped = str(exc)
    shutil.rmtree(work, ignore_errors=True)
    _set_aside_failed(production)
    return production


def _set_aside_failed(production: Production) -> None:
    """A render with a failed check is renamed ``video-<shape>.failed.mp4``, so it never sits there looking finished.
    It is kept, and still listed, so it can be looked at and judged."""
    for name, path in list(production.renders.items()):
        failed = [c for c in production.checks if c["render"] in (name, "all") and not c["ok"]]
        final = Path(path)
        if failed and final.is_file() and not final.name.endswith(".failed.mp4"):
            aside = final.with_name(final.stem + ".failed.mp4")
            aside.unlink(missing_ok=True)
            final.replace(aside)
            production.renders[name] = str(aside)


def _write_record(production: Production, brief: str) -> None:
    record = {
        "schema": "proofhouse.studio/v1",
        "proofhouse_version": __version__,
        "brief": brief,
        "title": production.title,
        "stopped": production.stopped,
        "spent_usd_estimated": format(production.spent_usd, "f"),
        "shots": [vars(s) for s in production.shots],
        "beats": production.beats,
        "voice_file": production.voice_file,
        "music_file": production.music_file,
        "renders": production.renders,
        "checks": production.checks,
        "calls": production.calls,
        "ffmpeg": [" ".join(c) for c in production.commands],
    }
    (production.folder / "studio.json").write_text(json.dumps(record, indent=2, default=str) + "\n", encoding="utf-8")
