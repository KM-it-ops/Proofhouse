"""The video production line: one brief in, finished videos out.

1. **Script and shot list.** A text model (any provider) writes the narration,
   the shots (what each shows, how long, the on-screen words) and a music brief.
2. **Visuals.** Each shot is generated by an image or video service (any media
   service). A still image gets a slow push-in so it moves.
3. **Voice-over and music.** A speech service reads the narration; a music
   service, or a file you give, makes the bed.
4. **Edit.** FFmpeg cuts every shot to length and frames it for each format,
   joins the shots, mixes the voice over the music (the music sits lower and
   loops if short), and burns in the captions.
5. **Renders.** Landscape 16:9, vertical 9:16 and square 1:1, plus a caption
   file (SRT).
6. **Checks.** Each render is measured: length, frame size, sound present,
   captions match the script word for word.

Every paid call goes through the spend gate; one spending limit covers the
whole production. Everything is kept in one folder: script, shots, audio,
renders, and ``studio.json`` with every call, cost, FFmpeg command and check.
"""

from __future__ import annotations

import json
import re
import shutil
import subprocess
from dataclasses import dataclass, field
from decimal import Decimal, InvalidOperation
from pathlib import Path
from typing import Any

from . import __version__, live, media, providers

FORMATS = {"16x9": (1920, 1080), "9x16": (1080, 1920), "1x1": (1080, 1080)}
FPS = 30

_SCRIPT = (
    "You are a video producer. Plan a finished video for the brief below, about {seconds} seconds long. "
    "Reply with JSON only, in this shape: "
    '{{"title": "...", "voiceover": "the full narration, spoken naturally", '
    '"shots": [{{"seconds": 4, "visual": "a detailed prompt for an image or video model: subject, setting, camera, '
    'light, style", "caption": "the exact words shown on screen (short)"}}], "music": "a prompt for the music bed: '
    'genre, mood, tempo"}}. The shots must add up to about {seconds} seconds; use 4 to 8 shots.\n\nBRIEF:\n{brief}'
)


class StudioError(Exception):
    """The production cannot start or cannot continue; the message says why."""


@dataclass
class Shot:
    seconds: int
    visual: str
    caption: str
    file: str | None = None


@dataclass
class Production:
    folder: Path
    title: str = ""
    voiceover: str = ""
    music_brief: str = ""
    shots: list[Shot] = field(default_factory=list)
    voice_file: str | None = None
    music_file: str | None = None
    renders: dict[str, str] = field(default_factory=dict)
    checks: list[dict[str, Any]] = field(default_factory=list)
    calls: list[dict[str, Any]] = field(default_factory=list)
    commands: list[list[str]] = field(default_factory=list)
    spent_usd: Decimal = Decimal(0)
    stopped: str = "finished"


class _Budget:
    def __init__(self, limit: str | None) -> None:
        try:
            self.left = Decimal(limit) if limit is not None else None
        except InvalidOperation:
            raise StudioError("--max-cost-usd must be a decimal such as 5.00") from None
        self.spent = Decimal(0)

    def next_limit(self) -> str | None:
        if self.left is None:
            return None
        if self.left <= 0:
            raise StudioError("spending limit reached")
        return format(self.left, "f")

    def charge(self, figure: Any) -> None:
        try:
            amount = Decimal(str(figure))
        except (InvalidOperation, ValueError):
            return
        if amount.is_finite() and amount >= 0:
            self.spent += amount
            if self.left is not None:
                self.left -= amount


def _json_object(text: str | None) -> dict[str, Any]:
    match = re.search(r"\{.*\}", text or "", flags=re.S)
    try:
        data = json.loads(match.group(0)) if match else None
    except ValueError:
        data = None
    if not isinstance(data, dict):
        raise StudioError("the script writer did not return the planned JSON; try another model")
    return data


def plan_from(data: dict[str, Any], seconds: int) -> tuple[str, str, str, list[Shot]]:
    shots = []
    for raw in data.get("shots") or []:
        if not isinstance(raw, dict) or not str(raw.get("visual", "")).strip():
            continue
        try:
            length = max(1, min(20, int(round(float(raw.get("seconds", 4))))))
        except (TypeError, ValueError):
            length = 4
        shots.append(Shot(length, str(raw["visual"]).strip(), str(raw.get("caption", "")).strip()))
    if not shots:
        raise StudioError("the script has no shots")
    total = sum(s.seconds for s in shots)
    if seconds and abs(total - seconds) > max(2, seconds // 10):  # stretch or shrink to the asked length
        scale = seconds / total
        for shot in shots:
            shot.seconds = max(1, round(shot.seconds * scale))
        shots[-1].seconds = max(1, shots[-1].seconds + seconds - sum(s.seconds for s in shots))
    return str(data.get("title", "")).strip(), str(data.get("voiceover", "")).strip(), str(data.get("music", "")).strip(), shots


def srt(shots: list[Shot]) -> str:
    def stamp(t: int) -> str:
        return f"{t // 3600:02d}:{t // 60 % 60:02d}:{t % 60:02d},000"

    blocks, start = [], 0
    for index, shot in enumerate(shots, start=1):
        if shot.caption:
            blocks.append(f"{index}\n{stamp(start)} --> {stamp(start + shot.seconds)}\n{shot.caption}\n")
        start += shot.seconds
    return "\n".join(blocks)


def shot_command(source: Path, kind: str, seconds: float, size: tuple[int, int], out: Path) -> list[str]:
    w, h = size
    frames = round(seconds * FPS)
    if kind == "image":
        vf = (f"scale={2 * w}:{2 * h}:force_original_aspect_ratio=increase,crop={2 * w}:{2 * h},"
              f"zoompan=z='min(zoom+0.0008,1.12)':x='iw/2-(iw/zoom/2)':y='ih/2-(ih/zoom/2)':d={frames}:s={w}x{h}:fps={FPS},"
              "format=yuv420p")
        return ["ffmpeg", "-y", "-loglevel", "error", "-i", str(source), "-vf", vf, "-frames:v", str(frames),
                "-c:v", "libx264", "-preset", "veryfast", "-an", str(out)]
    vf = f"scale={w}:{h}:force_original_aspect_ratio=increase,crop={w}:{h},fps={FPS},format=yuv420p"
    return ["ffmpeg", "-y", "-loglevel", "error", "-stream_loop", "-1", "-i", str(source), "-t", str(seconds), "-vf", vf,
            "-c:v", "libx264", "-preset", "veryfast", "-an", str(out)]


def caption_style(size: tuple[int, int]) -> str:
    """Caption style sized from the short side of the frame, so tall formats do not get oversized text.

    Captions are laid out on a 288-line grid that is stretched to the frame height, so sizes are given on that grid.
    """
    w, h = size
    grid = 288 / h
    short = min(w, h)
    return f"Fontsize={round(short * 0.07 * grid, 1)},Outline={max(1.5, round(short * 0.006 * grid, 1))},Shadow=1,MarginV=40"


DISSOLVE = 0.5
LOUDNESS = "loudnorm=I=-16:TP=-1.5:LRA=9,aresample=48000"


def dissolve_length(shots: list[Shot]) -> float:
    """How long neighbouring shots overlap: half a second, less when a shot is too short to give that much."""
    if len(shots) < 2:
        return 0.0
    return min(DISSOLVE, min(s.seconds for s in shots) / 2)


def join_command(clips: list[Path], seconds: list[int], dissolve: float, out: Path) -> list[str]:
    """Join the shots with dissolves; the film keeps the length of the shots added up, so the captions stay on time."""
    cmd = ["ffmpeg", "-y", "-loglevel", "error"]
    for clip in clips:
        cmd += ["-i", str(clip)]
    graph, label, start = [], "[0:v]", seconds[0]
    for index in range(1, len(clips)):
        last = index == len(clips) - 1
        graph.append(f"{label}[{index}:v]xfade=transition=fade:duration={dissolve}:offset={round(start - dissolve, 3)}"
                     f"[{'v' if last else f'x{index}'}]")
        label = f"[x{index}]"
        start += seconds[index]
    return cmd + ["-filter_complex", ";".join(graph), "-map", "[v]", "-c:v", "libx264", "-preset", "veryfast",
                  "-crf", "14", "-pix_fmt", "yuv420p", str(out)]


def final_command(joined: Path, voice: Path | None, music: Path | None, total: int, captions: bool, out: Path,
                  size: tuple[int, int] = (1920, 1080)) -> list[str]:
    """Fade the picture and sound in and out; clean the voice, dip the music under it, level the mix."""
    cmd = ["ffmpeg", "-y", "-loglevel", "error", "-i", str(joined)]
    inputs = []
    if voice:
        cmd += ["-i", str(voice)]
        inputs.append("voice")
    if music:
        cmd += ["-stream_loop", "-1", "-i", str(music)]
        inputs.append("music")
    edge = round(min(0.5, total / 6), 3)
    fades = f"fade=t=in:st=0:d={edge},fade=t=out:st={round(total - edge, 3)}:d={edge}"
    picture = f"subtitles=captions.srt:force_style='{caption_style(size)}'," + fades if captions else fades
    graph = []
    labels = []
    for index, name in enumerate(inputs, start=1):
        fit = f"apad=whole_dur={total},atrim=0:{total}"
        if name == "voice":
            graph.append(f"[{index}:a]highpass=f=80,acompressor=threshold=-18dB:ratio=3:attack=5:release=120,{fit}[voice]")
        else:
            graph.append(f"[{index}:a]volume={0.6 if voice else 1.0},{fit}[music]")
        labels.append(f"[{name}]")
    if len(labels) == 2:
        graph.append("[voice]asplit=2[voice_mix][voice_key]")
        graph.append("[music][voice_key]sidechaincompress=threshold=0.03:ratio=6:attack=25:release=450:makeup=1[ducked]")
        graph.append("[voice_mix][ducked]amix=inputs=2:duration=first:normalize=0[mixed]")
        labels = ["[mixed]"]
    if labels:
        graph.append(f"{labels[0]}{LOUDNESS},afade=t=out:st={round(total - edge, 3)}:d={edge}[a]")
    if graph or captions:
        graph.insert(0, f"[0:v]{picture}[v]")
        cmd += ["-filter_complex", ";".join(graph), "-map", "[v]"]
    else:
        cmd += ["-vf", picture, "-map", "0:v"]
    if labels:
        cmd += ["-map", "[a]", "-c:a", "aac", "-b:a", "192k"]
    cmd += ["-c:v", "libx264", "-preset", "veryfast", "-crf", "20", "-pix_fmt", "yuv420p", "-t", str(total),
            "-movflags", "+faststart", str(out)]
    return cmd


def probe(path: Path) -> dict[str, Any]:
    run = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration:stream=codec_type,width,height",
                          "-of", "json", str(path)], capture_output=True, text=True, check=False)
    data = json.loads(run.stdout or "{}")
    video = next((s for s in data.get("streams", []) if s.get("codec_type") == "video"), {})
    return {"seconds": float(data.get("format", {}).get("duration", 0) or 0), "width": video.get("width"),
            "height": video.get("height"), "audio": any(s.get("codec_type") == "audio" for s in data.get("streams", []))}


def _run(cmd: list[str], cwd: Path, production: Production) -> None:
    production.commands.append(cmd)
    done = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, check=False)
    if done.returncode != 0:
        raise StudioError(f"ffmpeg failed: {(done.stderr or '').strip()[-400:]}")


def produce(
    brief: str,
    *,
    provider_id: str,
    model: str,
    visual_provider: str,
    visual_model: str,
    visual_kind: str = "image",
    voice_provider: str | None = None,
    voice_model: str | None = None,
    voice: str | None = None,
    music_provider: str | None = None,
    music_model: str | None = None,
    music_file: Path | None = None,
    seconds: int = 30,
    formats: tuple[str, ...] = ("16x9", "9x16", "1x1"),
    captions: bool = True,
    max_cost_usd: str | None = None,
    out_dir: Path,
    size_scale: float = 1.0,
    text_transport: live.Transport | None = None,
    media_transport: Any = None,
    media_get: Any = None,
) -> Production:
    for tool in ("ffmpeg", "ffprobe"):
        if shutil.which(tool) is None:
            raise StudioError(f"{tool} is not installed; install FFmpeg (https://ffmpeg.org) and try again")
    if visual_kind not in ("image", "video"):
        raise StudioError("--visual-kind must be image or video")
    unknown = [f for f in formats if f not in FORMATS]
    if unknown:
        raise StudioError(f"unknown format {', '.join(unknown)}; use {', '.join(FORMATS)}")
    if not 3 <= seconds <= 600:
        raise StudioError("--seconds must be 3 to 600")
    paid = [p for p in (providers.find(provider_id),) if p is not None and not p.local]
    for service in (visual_provider, voice_provider, music_provider):
        found = media.find(service) if service else None
        if found is not None and not found.local:
            paid.append(found)
    if paid and max_cost_usd is None:
        raise StudioError("name one spending limit for the whole video (--max-cost-usd)")
    budget = _Budget(max_cost_usd)
    out_dir = out_dir.resolve()  # FFmpeg runs inside this folder, so every path in it must be absolute
    out_dir.mkdir(parents=True, exist_ok=False)
    production = Production(out_dir)

    def record(role: str, result: Any, figure: Any) -> None:
        production.calls.append({"role": role, "status": result.status, "code": result.code, "usd": figure})
        if result.status == "refused" and result.code == "PHC-COST-0001":
            raise StudioError("spending limit reached")
        if result.status != "success":
            raise StudioError(f"{role}: {result.message}")

    try:
        reply = live.run_prompt(provider_id, model, prompt=_SCRIPT.format(seconds=seconds, brief=brief),
                                max_output_tokens=2048, max_cost_usd=budget.next_limit(), transport=text_transport)
        figure = (reply.cost or {}).get("usd")
        budget.charge(figure if reply.status != "refused" else 0)
        record("script", reply, figure)
        title, narration, music_brief, shots = plan_from(_json_object(reply.output_text), seconds)
        production.title, production.voiceover, production.music_brief, production.shots = title, narration, music_brief, shots
        (out_dir / "script.json").write_text(json.dumps({"title": title, "voiceover": narration, "music": music_brief,
                                                          "shots": [vars(s) for s in shots]}, indent=2) + "\n", encoding="utf-8")

        def make_media(kind: str, service: str, model_id: str, prompt: str, target: Path, params: dict[str, Any]) -> str:
            result = media.generate(kind, service, model_id, prompt=prompt, out=target, params=params,
                                    max_cost_usd=budget.next_limit(), transport=media_transport, get=media_get)
            figure = (result.cost or {}).get("usd")
            if result.status != "refused":
                budget.charge(figure)
            record(f"{kind}: {prompt[:40]}", result, figure)
            return str(result.path)

        (out_dir / "shots").mkdir()
        for index, shot in enumerate(shots, start=1):
            params = {"seconds": shot.seconds} if visual_kind == "video" else {"size": "1792x1024"}
            shot.file = make_media(visual_kind, visual_provider, visual_model, shot.visual, out_dir / "shots" / f"shot-{index:02d}", params)
        if voice_provider and narration:
            production.voice_file = make_media("speech", voice_provider, voice_model or "", narration, out_dir / "voice",
                                               {"voice": voice} if voice else {})
        if music_file is not None:
            production.music_file = str(shutil.copy2(music_file, out_dir / f"music{music_file.suffix}"))
        elif music_provider and music_brief:
            production.music_file = make_media("music", music_provider, music_model or "", music_brief, out_dir / "music",
                                               {"seconds": sum(s.seconds for s in shots)})
    except StudioError as exc:
        production.stopped = str(exc)
        production.spent_usd = budget.spent
        _write_record(production, brief)
        return production

    production = assemble(
        out_dir, shots, visual_kind=visual_kind, formats=formats, size_scale=size_scale, captions=captions,
        voice_file=production.voice_file, music_file=production.music_file, production=production,
    )
    production.spent_usd = budget.spent
    _write_record(production, brief)
    return production


_CLIP_SUFFIXES = frozenset({".mp4", ".webm", ".mov", ".mkv"})


def assemble(
    out_dir: Path,
    shots: list[Shot],
    *,
    visual_kind: str,
    formats: tuple[str, ...],
    size_scale: float = 1.0,
    captions: bool = True,
    voice_file: str | None = None,
    music_file: str | None = None,
    production: Production | None = None,
) -> Production:
    """Cut shots to length, join, mix audio, burn captions, and measure each render."""
    if production is None:
        production = Production(out_dir)
    else:
        production.folder = out_dir
    production.voice_file = voice_file
    production.music_file = music_file
    total = sum(s.seconds for s in shots)
    (out_dir / "captions.srt").write_text(srt(shots), encoding="utf-8")
    work = out_dir / "work"
    work.mkdir()
    try:
        if production.voice_file:
            spoken = probe(Path(production.voice_file))["seconds"]
            production.checks.append({
                "render": "all", "check": "voice fits the film", "ok": spoken <= total + 0.25,
                "detail": f"{spoken:.1f}s of voice in a {total}s film" + (
                    f": the last {spoken - total:.1f}s of speech is cut off; shorten the script or lengthen the shots"
                    if spoken > total + 0.25 else "")})
        for name in formats:
            w, h = FORMATS[name]
            size = (int(w * size_scale) // 2 * 2, int(h * size_scale) // 2 * 2)
            clips = []
            dissolve = dissolve_length(shots)
            for index, shot in enumerate(shots, start=1):
                if not shot.file:
                    raise StudioError(f"shot {index} has no file")
                clip = work / f"{name}-shot-{index:02d}.mp4"
                kind = visual_kind if visual_kind != "mixed" else ("video" if Path(shot.file).suffix.lower() in _CLIP_SUFFIXES else "image")
                # every shot after the first starts one dissolve early, under the end of the shot before it
                _run(shot_command(Path(shot.file), kind, shot.seconds + (dissolve if index > 1 else 0), size, clip), out_dir, production)
                clips.append(clip)
            joined = work / f"{name}-joined.mp4"
            if len(clips) == 1:
                joined = clips[0]
            else:
                _run(join_command(clips, [s.seconds for s in shots], dissolve, joined), work, production)
            final = out_dir / f"video-{name}.mp4"
            has_captions = captions and any(s.caption for s in shots)
            _run(final_command(joined, Path(production.voice_file) if production.voice_file else None,
                               Path(production.music_file) if production.music_file else None, total, has_captions, final, size),
                 out_dir, production)
            production.renders[name] = str(final)
            measured = probe(final)
            production.checks += [
                {"render": name, "check": "length", "ok": abs(measured["seconds"] - total) <= max(1.0, total * 0.05),
                 "detail": f"{measured['seconds']:.1f}s of {total}s"},
                {"render": name, "check": "frame size", "ok": (measured["width"], measured["height"]) == size,
                 "detail": f"{measured['width']}x{measured['height']}"},
                {"render": name, "check": "sound", "ok": measured["audio"] == bool(production.voice_file or production.music_file),
                 "detail": "voice/music present" if measured["audio"] else "silent"},
            ]
        production.checks.append({"render": "all", "check": "captions match the script",
                                  "ok": srt(shots) == (out_dir / "captions.srt").read_text(encoding="utf-8"),
                                  "detail": f"{sum(1 for s in shots if s.caption)} captions"})
    except StudioError as exc:
        production.stopped = str(exc)
    shutil.rmtree(work, ignore_errors=True)
    return production


def _write_record(production: Production, brief: str) -> None:
    record = {
        "schema": "proofhouse.studio/v1",
        "proofhouse_version": __version__,
        "brief": brief,
        "title": production.title,
        "stopped": production.stopped,
        "spent_usd_estimated": format(production.spent_usd, "f"),
        "shots": [vars(s) for s in production.shots],
        "voice_file": production.voice_file,
        "music_file": production.music_file,
        "renders": production.renders,
        "checks": production.checks,
        "calls": production.calls,
        "ffmpeg": [" ".join(c) for c in production.commands],
    }
    (production.folder / "studio.json").write_text(json.dumps(record, indent=2, default=str) + "\n", encoding="utf-8")
